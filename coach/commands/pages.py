import os

from coach import dates, pages
from coach.commands import arg, command
from coach.errors import UsageError


@command(
    "pages render",
    help="Render this-week.md (the brief), README.md (the dashboard) and progress.md as of now",
    args=(arg("--only", choices=pages.KINDS, help="render one page"),
          arg("--replace-readme", action="store_true",
              help="replace a README.md that coach did not generate with the dashboard")),
    writes=True,
)
def render(args, ctx):
    kinds = (args.only,) if args.only else pages.KINDS
    report = pages.write(ctx.root, ctx.now(), kinds, args.replace_readme, args.dry_run)
    if report["replaced_readme"]:
        ctx.warn("README.md was not generated by coach; it is " + ("to be " if args.dry_run else "now ")
                 + "replaced by the dashboard (the old text stays in git history)")
    return report


@command(
    "pages show",
    help="One page as a fresh render would write it now, without writing it",
    args=(arg("kind", choices=pages.KINDS, help="brief, dashboard or progress"),),
)
def show(args, ctx):
    path = pages.PAGE_PATHS[args.kind]
    text = pages.render_all(ctx.root, ctx.now(), (args.kind,))[path]
    return {"kind": args.kind, "path": path, "as_of": pages.timestamp(pages.as_of_moment(ctx.now())), "text": text}


@command(
    "pages publish",
    help="Re-render the pages, then commit them with the approved overlay and the newest record, and push",
    args=(arg("--overlay", required=True, metavar="ID", help="the approved overlay of the programming pass"),
          arg("--record", metavar="D", help="the check-in record's date (default: the newest record)")),
    writes=True,
    git_write=True,
)
def publish(args, ctx):
    record = None
    if args.record is not None:
        try:
            record = dates.parse_date(args.record)
        except ValueError as exc:
            raise UsageError(f"--record: {exc}") from None
    env = dict(os.environ)
    env.update(ctx.env)
    return pages.publish(ctx.root, args.overlay, ctx.now(), record, args.dry_run, env)
