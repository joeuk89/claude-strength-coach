def readme_owner_problem(root):
    """Why `README.md` may not be overwritten (it exists and coach did not generate it), or None."""
    path = Path(root) / paths.DASHBOARD
    if path.is_file() and not is_generated(path.read_text(encoding="utf-8")):
        return ("README.md was not generated by coach (it has no generated-by header), so pages render will not "
                "overwrite it; run python3 -m coach pages render --replace-readme to make it the dashboard")
    return None


def write(root, now, kinds=KINDS, replace_readme=False, dry_run=False):
    """Render the pages and write them; refuses (exit 3) to replace a README coach did not generate."""
    root = Path(root)
    replaced = False
    if DASHBOARD in kinds:
        problem = readme_owner_problem(root)
        if problem and not replace_readme:
            raise RefusedError(problem)
        replaced = problem is not None
    view = _View(root, now)
    rendered = render_all(root, now, kinds, view)
    report = []
    for path, text in rendered.items():
        target = root / path
        before = target.read_text(encoding="utf-8") if target.is_file() else None
        if not dry_run:
            target.write_text(text, encoding="utf-8")
        report.append({"path": path, "changed": before != text, "written": not dry_run, "lines": text.count("\n")})
    return {"as_of": timestamp(as_of_moment(now)), "pages": report, "replaced_readme": replaced,
            "brief_overlay": brief_overlay(view), "dry_run": dry_run}


def freshness(root):
    """[(path, status, message)] for each page present: does it equal a fresh render at its own as-of time?"""
    root = Path(root)
    found = []
    for kind in KINDS:
        rel = PAGE_PATHS[kind]
        path = root / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        if kind == DASHBOARD and not is_generated(text):
            continue
        as_of = recorded_as_of(text)
        if as_of is None:
            found.append((rel, "fail", f"{rel} has no generated-by header with an as-of time; regenerate it with "
                                       f"python3 -m coach {RENDER_COMMAND}"))
            continue
        fresh = render_all(root, as_of, (kind,))[rel]
        if fresh != text:
            found.append((rel, "fail", f"{rel} differs from a fresh render as of {timestamp(as_of)} (hand-edited, or "
                                       f"its data changed); run python3 -m coach {RENDER_COMMAND}"))
        else:
            found.append((rel, "pass", f"{rel} matches a fresh render as of {timestamp(as_of)}"))
    return found


def publish_message(doc):
    return f"coach: publish week of {doc['span']['start']} ({doc['id']})"


_git = closeout.git


def require_work_tree(root, env=None):
    if shutil.which("git") is None:
        raise ConfigError("git is not installed, so the pages cannot be committed and pushed")
    if _git(root, "rev-parse", "--is-inside-work-tree", env=env).stdout.strip() != "true":
        raise RefusedError(f"{root} is not a git working tree, so there is nothing to publish to")


def _upstream(root, env):
    branch = _git(root, "symbolic-ref", "--quiet", "--short", "HEAD", env=env)
    if branch.returncode != 0:
        raise RefusedError("HEAD is not on a branch, so there is nothing to push; check out the instance's branch")
    name = branch.stdout.strip()
    remote = _git(root, "config", f"branch.{name}.remote", env=env).stdout.strip()
    merge = _git(root, "config", f"branch.{name}.merge", env=env).stdout.strip()
    if not remote or not merge:
        raise RefusedError(f"branch {name} has no upstream; set one with git push -u <remote> {name}, then publish")
    return name, remote, merge


def _ahead(root, env):
    """Commits on HEAD that the upstream's remote-tracking ref lacks, or None when that ref is unknown."""
    counted = _git(root, "rev-list", "--count", "@{upstream}..HEAD", env=env)
    return int(counted.stdout.strip()) if counted.returncode == 0 else None


def publish(root, overlay_id, now, record_date=None, dry_run=False, env=None, include=(), structural=False):
    """Render and publish the pages, applicable session sheets, overlay, record and approved training records (C38).

    `include` names the training-record files the brief's commit plan listed; `structural` admits
    data/program.json. Every refusal (exit 3) comes before anything is written. A rejected push
    exits 4 and keeps the commit.
    """
    root = Path(root)
    doc = overlay.load(root, overlay_id)
    if not overlay.is_approved(doc):
        raise RefusedError(f"overlay {overlay_id} is not approved (or was edited after approval); only an approved "
                           f"week is published: run python3 -m coach overlay approve {overlay_id} after the "
                           "athlete's go")
    found = checkin.records(root)
    if record_date is None:
        if not found:
            raise ValidationError("there is no check-in record to publish; write one with python3 -m coach checkin "
                                  "skeleton first")
        record = found[-1]
    else:
        day = dates.parse_date(str(record_date))
        record = next((r for r in found if r.date == day), None)
        if record is None:
            raise ValidationError(f"there is no check-in record check-ins/{day.isoformat()}.md")
    require_work_tree(root, env)
    branch, remote, merge = _upstream(root, env)
    publish_paths = [PAGE_PATHS[BRIEF], PAGE_PATHS[DASHBOARD], PAGE_PATHS[PROGRESS],
                     (paths.OVERLAYS_DIR / f"{overlay_id}.json").as_posix(), record.path.as_posix()]
    view = _View(root, now)
    include_sheets = not view.config.hevy.enabled
    if include_sheets:
        publish_paths.append(paths.SESSION_SHEETS.as_posix())
    records = closeout.select(root, include, structural, env)
    publish_paths += [row["path"] for row in records["included"]]
    staged = _git(root, "diff", "--cached", "--name-only", "--no-renames", "-z", env=env).stdout.split("\0")
    others = sorted(p for p in staged if p and p not in publish_paths)
    if others:
        raise RefusedError("the git index already holds staged changes to other files, which a publish would "
                           f"sweep up: {', '.join(others)}; commit or unstage them first")
    problem = readme_owner_problem(root)
    if problem:
        raise RefusedError(problem)
    current_id = view.week_overlay["id"] if view.week_overlay else None
    if current_id != overlay_id:
        raise RefusedError(f"the brief shows overlay {current_id or 'none'}, not {overlay_id}; publish the approved "
                           "overlay in force for the brief's coming week")
    sheet_text = sheets.render_sheets(root, overlay_id) if include_sheets else None
    message = publish_message(doc)
    report = {"overlay_id": overlay_id, "record": record.path.as_posix(), "paths": publish_paths, "message": message,
              "records": records, "branch": branch, "remote": remote, "upstream": merge, "commit": None,
              "pushed": False, "ahead": None, "dry_run": dry_run}
    if dry_run:
        return report
    report["rendered"] = write(root, now, KINDS)["pages"]
    if sheet_text is not None:
        (root / paths.SESSION_SHEETS).write_text(sheet_text, encoding="utf-8")
    if record.kind != checkin.UNRECOGNISED:
        checkin.skeleton(root, record.date, refresh=True, now=now)
    deleted = [row["path"] for row in records["included"] if row["change"] == "deleted"]
    removed = _git(root, "rm", "-q", "--cached", "--ignore-unmatch", "--", *deleted, env=env) if deleted else None
    if removed is not None and removed.returncode != 0:
        raise ValidationError(f"git rm failed: {removed.stderr.strip()}")
    added = _git(root, "add", "--", *(p for p in publish_paths if p not in deleted), env=env)
    if added.returncode != 0:
        raise ValidationError(f"git add failed: {added.stderr.strip()}")
    if _git(root, "diff", "--cached", "--quiet", env=env).returncode == 0:
        report["ahead"] = _ahead(root, env)
        return report
    committed = _git(root, "commit", "-q", "-m", message, env=env)
    if committed.returncode != 0:
        raise ValidationError(f"git commit failed: {committed.stderr.strip() or committed.stdout.strip()}")
    report["commit"] = _git(root, "rev-parse", "HEAD", env=env).stdout.strip()
    push_env = dict(os.environ if env is None else env, GIT_TERMINAL_PROMPT="0")
    try:
        pushed = _git(root, "push", remote, f"HEAD:{merge}", env=push_env)
        reason = None if pushed.returncode == 0 else (pushed.stderr.strip().splitlines() or ["no output"])[-1]
    except subprocess.TimeoutExpired as exc:
        reason = f"no answer after {exc.timeout:g} s"
    report["ahead"] = _ahead(root, env)
    if reason is not None:
        raise NetworkError(f"git push to {remote} failed ({reason}); the commit {report['commit'][:12]} is kept: "
                           "push it by hand with git push", data=report)
    report["pushed"] = True
    return report
