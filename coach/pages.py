def _load(load, show_hevy=True):
    return units.format_load(load, show_hevy=show_hevy)


def timestamp(moment):
    return moment.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def as_of_moment(now):
    """`now` to the second, in UTC: the as-of time a render records and is reproduced from."""
    return now.astimezone(timezone.utc).replace(microsecond=0)


def header(source, as_of):
    return (f"{GENERATED}{source} as of {timestamp(as_of)}; edit the data, then run: "
            f"python3 -m coach {RENDER_COMMAND} -->")


def is_generated(text):
    return text.startswith(GENERATED)


def recorded_as_of(text):
    """The as-of time in a page's C11 header, or None when the page has no such header."""
    match = _HEADER.match(text.split("\n", 1)[0])
    if not match or not match.group(2):
        return None
    try:
        return dates.parse_timestamp(match.group(2))
    except ValueError:
        return None


def _num(value):
    quantised = Decimal(str(value)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    text = format(quantised, "f").rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def _signed(value):
    if value is None:
        return "—"
    return "±0" if value == 0 else f"{'+' if value > 0 else ''}{_num(value)}"


def _long_date(day):
    day = dates.parse_date(day) if isinstance(day, str) else day
    return f"{day.day} {_MONTHS[day.month - 1]} {day.year}"


def _cell(value):
    return "" if value is None else str(value).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def _row(cells):
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _reps(set_):
    if set_.get("rep_range") is not None:
        return f"{set_['rep_range']['start']}–{set_['rep_range']['end']}"
    if set_.get("reps") is not None:
        return _num(set_["reps"])
    if set_.get("duration_seconds") is not None:
        return f"{_num(set_['duration_seconds'])} s"
    if set_.get("distance_meters") is not None:
        return f"{_num(set_['distance_meters'])} m"
    return "?"


def _set_load(line, set_, show_hevy=True):
    load = set_.get("load")
    if load is None:
        return None
    text = _load(load, show_hevy)
    return f"{text} {load['unit']}" if line["load_mode"] == "total" else text


def sets_text(line, show_hevy=True):
    """A line's working sets in C12 Target form without RPE: `3×5 @ 100 kg`, `3×8–10 @ 25/hand (Hevy: 50)`."""
    groups = []
    for set_ in (s for s in line["sets"] if overlay.is_working(s)):
        key = (_reps(set_), _set_load(line, set_, show_hevy))
        if groups and groups[-1][0] == key:
            groups[-1][1] += 1
        else:
            groups.append([key, 1])
    text = " + ".join(f"{count}×{reps}" + (f" @ {load}" if load else "") for (reps, load), count in groups)
    needs_load = any(s.get("load") is None and line["load_mode"] in units.LOADED_MODES
                     for s in line["sets"] if overlay.is_working(s))
    if needs_load:
        text += f" · {render.CHOOSE_THE_LOAD}"
    return text


def _change_text(line, show_hevy=True):
    """The line's `change`, with the Hevy value added when Hevy is on and it ends on a bare per-hand load."""
    change = line["change"]
    load = next((s["load"] for s in line["sets"] if overlay.is_working(s) and s.get("load")), None)
    if load is None:
        return change
    full = _load(load, show_hevy)
    short = full.split(" (Hevy: ", 1)[0]
    # The coach writes `22.5 → 25/hand`; with Hevy on, a dumbbell load on the page shows both numbers.
    if "/hand" in short and short != full and change.endswith(short):
        return change + full[len(short):]
    return change


def _change_reason(line):
    if line.get("override") and line["override"].get("reason"):
        return line["override"]["reason"]
    if line.get("provenance") and line["provenance"].get("rationale"):
        return line["provenance"]["rationale"]
    return line.get("target_note")


def _valid_overlays(root):
    found = []
    for overlay_id in overlay.ids(root):
        try:
            found.append(overlay.load(root, overlay_id))
        except ValidationError:
            continue
    return found


class _View:
    """Everything one render reads, loaded once and shared by the three pages."""

    def __init__(self, root, as_of):
        self.root = Path(root)
        self.as_of = as_of_moment(as_of)
        self.config = config_module.load(self.root)
        zone_name = self.config.athlete.timezone
        self.zone = dates.zone(zone_name) if zone_name else None
        self.today = self.as_of.astimezone(self.zone).date()
        self.week_starts = self.config.athlete.week_starts
        self.week = dates.week_span(self.today + timedelta(days=1), self.week_starts)
        self.unit = self.config.athlete.units
        self.show_hevy = self.config.hevy.enabled
        self.coaching_mode = coaching.mode(self.config)

    @cached_property
    def program(self):
        return history.load_optional(program, self.root)

    @cached_property
    def state(self):
        return history.load_optional(state, self.root)

    @cached_property
    def overlays(self):
        return _valid_overlays(self.root)

    @cached_property
    def library(self):
        return Library.load(self.root)

    @cached_property
    def week_overlay(self):
        """The overlay in force for the brief's week: the latest created of those in force on its days."""
        found = [hit[0] for hit in (overlay.pick_in_force(self.overlays, day) for day in self.week.days()) if hit]
        return max(found, key=lambda d: (dates.parse_timestamp(d["created_at"]), d["id"]), default=None)

    @cached_property
    def facts(self):
        rotation = None
        if self.state:
            rotation = {"position": self.state["rotation"]["position"],
                        "confirmed": self.state["rotation"]["confirmed"]}
        nutrition = nutrition_part.status(self.root, self.today)
        found = [r for r in checkin.records(self.root) if r.date <= self.today]
        due = checkin.due(self.root, self.today)
        tier = "deep" if checkin.deep_reasons(found, due.due_date or self.today) else "weekly"
        return {
            "week": self.week.label(), "week_start": self.week.start.isoformat(),
            "overlay_id": self.week_overlay["id"] if self.week_overlay else None,
            "rotation": rotation,
            "phase": nutrition.get("phase") if nutrition else None,
            "checkin": {"last": due.last.date.isoformat() if due.last else None,
                        "due_date": due.due_date.isoformat() if due.due_date else None,
                        "tier": tier, "days_since": due.days_since, "mode": due.mode},
        }

    @cached_property
    def parts(self):
        ctx = page_parts.PageContext(self.root, self.as_of, self.today, self.week_overlay, self.program, self.state)
        return page_parts.collect(ctx)

    def slot(self, name):
        return list(self.parts.get(name, []))

    def tier(self, session_id):
        sessions = self.program["sessions"] if self.program else []
        found = next((s for s in sessions if s["id"] == session_id), None)
        return found["tier"] if found else "core"

    def name(self, exercise_id):
        entry = self.library.get(exercise_id)
        return entry["name"] if entry else exercise_id

    def _stripped(self, exercise_id):
        return _TRAILING_PARENTHESIS.sub("", self.name(exercise_id)) or self.name(exercise_id)

    @cached_property
    def _named_ids(self):
        """{name without its trailing parenthesis: exercise ids} over every exercise the pages can name."""
        ids = {line["exercise_id"] for session in (self.program or {}).get("sessions", [])
               for line in session["exercises"]}
        ids |= {line["exercise_id"] for doc in self.overlays for session in doc["sessions"]
                for line in session["exercises"]}
        ids |= set(self.series)
        found = {}
        for exercise_id in ids:
            found.setdefault(self._stripped(exercise_id), set()).add(exercise_id)
        return found

    def short_name(self, exercise_id):
        """The library name without its trailing parenthesis, unless another exercise would then read the same."""
        stripped = self._stripped(exercise_id)
        return stripped if self._named_ids.get(stripped, set()) <= {exercise_id} else self.name(exercise_id)

    def mode(self, exercise_id):
        return self.library.effective_load_mode(exercise_id) if self.library.get(exercise_id) else None

    def per_hand(self, exercise_id):
        return "/hand" if self.mode(exercise_id) == "per_hand_x2" else ""

    def e1rm_text(self, exercise_id, value):
        return f"{_num(value)} {self.unit}{self.per_hand(exercise_id)}"

    def program_order(self, exercise_ids):
        """`exercise_ids` with the program's exercises first, in session order, then the rest by name."""
        order = [line["exercise_id"] for session in (self.program or {}).get("sessions", [])
                 for line in session["exercises"]]
        return sorted(exercise_ids, key=lambda i: (order.index(i) if i in order else len(order), self.name(i)))

    @cached_property
    def week_rows(self):
        """Adherence rows for the brief's week: every session of the overlay in force on each day, by date."""
        found = stats.adherence(self.root, span=(self.week.start, self.week.end), today=self.today, as_of=self.as_of)
        return found["sessions"]

    def session_of(self, row):
        doc = next(d for d in self.overlays if d["id"] == row["overlay_id"])
        session = next(s for s in doc["sessions"] if s["session_id"] == row["session_id"] and s["date"] == row["date"])
        return doc, session

    @cached_property
    def capacity(self):
        return stats.e1rm_series(self.root, as_of=self.as_of)

    @cached_property
    def series(self):
        return self.capacity["series"]

    @cached_property
    def weeks(self):
        """(span, complete, core trained, core planned) for each week from the first overlay to the brief's week.

        `complete` is None for a week with no planned core session (C38 core-complete week).
        """
        if not self.overlays:
            return []
        first = min(dates.parse_date(d["span"]["start"]) for d in self.overlays)
        end = self.week.start - timedelta(days=1)
        if first > end:
            return []
        rows = stats.adherence(self.root, span=(first, end), today=self.today, as_of=self.as_of)["sessions"]
        not_done = [a for a in history.annotations(self.root, "external", self.as_of) if a["done"] is False]
        found, day = [], dates.week_span(first, self.week_starts).start
        while day <= end:
            span = dates.week_span(day, self.week_starts)
            core = [r for r in rows
                    if span.contains(dates.parse_date(r["date"])) and self.tier(r["session_id"]) == "core"]
            trained = sum(1 for r in core if r["status"] == "trained")
            complete = None
            if core:
                complete = trained == len(core) and not any(span.contains(dates.parse_date(a["date"]))
                                                            for a in not_done)
            found.append((span, complete, trained, len(core)))
            day = span.end + timedelta(days=1)
        return found

    @cached_property
    def streak(self):
        current = 0
        for _, complete, _, _ in reversed(self.weeks):
            if not complete:
                break
            current += 1
        longest = run = 0
        for _, complete, _, _ in self.weeks:
            run = run + 1 if complete else 0
            longest = max(longest, run)
        return current, longest

    @cached_property
    def body_weights(self):
        """[(date, weight)] of Hevy body measurements in bodyweight units dated by `as_of`, oldest first."""
        unit = self.config.athlete.bodyweight_units
        found = []
        for reading in HevyCache(self.root).body_measurements() or []:
            day = (reading.get("date") or "")[:10]
            if reading.get("weight_kg") and day and day <= self.today.isoformat():
                found.append((dates.parse_date(day), units.from_hevy_kg(reading["weight_kg"], "total", unit)))
        return sorted(found)

    def weekly_body_weights(self):
        """[(week start, mean weight)], oldest first."""
        by_week = {}
        for day, weight in self.body_weights:
            by_week.setdefault(dates.week_span(day, self.week_starts).start, []).append(weight)
        return [(start, sum(values) / len(values)) for start, values in sorted(by_week.items())]

    def header_line(self):
        facts = self.facts
        parts = [f"**Week of {render.short_date(facts['week_start'])}**"]
        rotation = facts["rotation"]
        if rotation and rotation["position"]:
            words = rotation["position"].replace("-", " ").replace("_", " ").split()
            label = " ".join(w.upper() if len(w) == 1 else w.capitalize() for w in words)
            parts.append(f"{label} ({'confirmed' if rotation['confirmed'] else 'not confirmed'})")
        phase = self.slot("brief.header.phase")
        if phase:
            parts.append(phase[-1].text)
        if self.coaching_mode == coaching.RUN:
            parts.append("run mode")
        parts.append(_checkin_text(facts["checkin"], self.today))
        return " · ".join(parts)

    def key(self, session):
        """The session's first exercise and its working sets: `Back Squat 3×5 @ 100 kg`."""
        if not session["exercises"]:
            return ""
        first = session["exercises"][0]
        return f"{self.short_name(first['exercise_id'])} {sets_text(first, self.show_hevy)}"

    def session_rows(self):
        lines = []
        for row in self.week_rows:
            _, session = self.session_of(row)
            day = dates.parse_date(row["date"])
            lines.append(_row([f"{_DAYS[day.weekday()]} {day.day}", row["title"], self.tier(row["session_id"]),
                               self.key(session), self.done(row)]))
        return lines

    def done(self, row):
        if row["status"] == "trained":
            return TRAINED
        if row["status"] == "missed" and not (row["date"] == self.today.isoformat() and row["tag"] == "untagged"):
            return MISSED
        return ""

    def sessions_table(self):
        if not self.week_rows:
            return ["No sessions planned this week."]
        return list(SESSIONS_HEADER) + self.session_rows()

    def changed(self):
        found = []
        for row in self.week_rows:
            _, session = self.session_of(row)
            for line in session["exercises"]:
                if line.get("change"):
                    text = f"{self.short_name(line['exercise_id'])} {_change_text(line, self.show_hevy)}"
                    reason = _change_reason(line)
                    found.append(f"{text}: {reason}" if reason else text)
        return found

    def week_docs(self):
        ids = []
        for row in self.week_rows:
            if row["overlay_id"] not in ids:
                ids.append(row["overlay_id"])
        if self.week_overlay and self.week_overlay["id"] not in ids:
            ids.append(self.week_overlay["id"])
        return [d for i in ids for d in self.overlays if d["id"] == i]

    def open_flags(self):
        found = flags_module.for_mode([f for doc in self.week_docs() for f in doc["flags"]], self.coaching_mode)
        return [f for f in found if not f["resolved"] and f["severity"] in ("block", "warn")]

    def watch(self):
        items = [Item(f["message"], PRIORITY[f["severity"]]) for f in self.open_flags()]
        return _ranked(items + self.slot("brief.watch"), WATCH_LIMIT)

    def if_you_miss(self):
        replaced = self.slot("brief.if_you_miss")
        if replaced:
            return [item.text for item in replaced]
        return ["No missed-day rules yet: tell the coach, and the rest of the week is reprogrammed."]

    def wins(self):
        items = []
        start = (self.today - timedelta(days=WIN_DAYS - 1)).isoformat()
        for exercise_id, points in sorted(self.series.items(), key=lambda pair: self.name(pair[0])):
            if self.mode(exercise_id) not in stats.SERIES_MODES:
                continue
            best = max(points, key=lambda p: (p["e1rm"], p["date"]))
            earlier = [p["e1rm"] for p in points if p["date"] < best["date"]]
            if best["date"] >= start and earlier and best["e1rm"] > max(earlier):
                items.append(Item(f"New best e1RM: {self.short_name(exercise_id)} "
                                  f"{self.e1rm_text(exercise_id, best['e1rm'])} "
                                  f"({render.day_label(best['date'])})", PRIORITY["e1rm"]))
        current, _ = self.streak
        if current >= STREAK_WIN_WEEKS:
            items.append(Item(f"Core-complete streak: {current} weeks", PRIORITY["streak"]))
        last = self.weeks[-1] if self.weeks else None
        if last and last[3] and last[2] == last[3]:
            items.append(Item(f"Every core session trained last week ({last[2]} of {last[3]})",
                              PRIORITY["last_week"]))
        return _ranked(items + self.slot("brief.wins"), WINS_LIMIT)


def _ranked(items, limit):
    return [item.text for item in sorted(items, key=lambda item: item.priority)][:limit]


def _checkin_text(found, today):
    tier = found["tier"]
    if found["due_date"] is None:
        return f"First check-in due ({tier})"
    due = dates.parse_date(found["due_date"])
    if due < today:
        return f"Check-in overdue since {render.day_label(due)} ({tier})"
    return f"Check-in due {render.day_label(due)} ({tier})"


def header_facts(root, as_of):
    """The brief header's facts, computed once for the brief, the dashboard and `coach status` (C38)."""
    return _View(root, as_of).facts


def _bullets(texts):
    return [f"- {text}" for text in texts]


def _brief_text(view, sections):
    lines = [header(_brief_source(view), view.as_of), view.header_line()]
    for heading, body, items, tail in sections:
        lines += ["", f"## {heading}"] + body + _bullets(items) + tail
    return "\n".join(lines) + "\n"


def _brief_source(view):
    if view.week_overlay is None:
        return paths.OVERLAYS_DIR.as_posix() + "/"
    return (paths.OVERLAYS_DIR / f"{view.week_overlay['id']}.json").as_posix()


def render_brief(root, as_of, view=None):
    """`this-week.md`: the brief for the week holding the day after `as_of`, at most 60 lines."""
    view = view or _View(root, as_of)
    focus = [view.week_overlay["focus"] if view.week_overlay else
             "No overlay covers this week yet; the next programming pass writes one."]
    extra = [item.text for item in view.slot("brief.lines")]
    if extra:
        focus += [""] + _bullets(extra)
    sessions = view.sessions_table()
    footer = [item.text for item in view.slot("brief.sessions_footer")]
    if footer:
        sessions += [""] + footer
    changed = view.changed()
    items = {"Changed": changed[:CHANGED_LIMIT] or ["No changes this week."],
             "Watch": view.watch() or ["Nothing flagged."],
             "Wins": view.wins() or ["None yet; they come from new bests and complete weeks."],
             IF_YOU_MISS: view.if_you_miss()}
    shown = {heading: len(found) for heading, found in items.items()}

    def build():
        sections = [("Focus", focus, [], []), ("Sessions", sessions, [], [])]
        if shown["Changed"]:
            more = len(changed) - shown["Changed"] if changed else 0
            tail = [f"- and {more} more in the check-in"] if more else []
            sections.append(("Changed", [], items["Changed"][:shown["Changed"]], tail))
        if shown["Watch"]:
            sections.append(("Watch", [], items["Watch"][:shown["Watch"]], []))
        more = len(items[IF_YOU_MISS]) - shown[IF_YOU_MISS]
        tail = [f"- and {more} more in {paths.ROUTINE_PROGRAM_PAGE.as_posix()}"] if more else []
        sections.append((IF_YOU_MISS, [], items[IF_YOU_MISS][:shown[IF_YOU_MISS]], tail))
        if shown["Wins"]:
            sections.append(("Wins", [], items["Wins"][:shown["Wins"]], []))
        return _brief_text(view, sections)

    text = build()
    for heading in CUT_ORDER:
        while text.count("\n") > BRIEF_LINE_CEILING and shown[heading]:
            shown[heading] -= 1
            text = build()
    return text


def render_dashboard(root, as_of, view=None):
    """`README.md`: the status block, the week's sessions, a progress summary and links."""
    view = view or _View(root, as_of)
    status = [view.header_line()]
    if view.state:
        status.append(block_module.status_line(view.root) or f"Block: {view.state['block']['id']}")
    records = [r for r in checkin.records(view.root) if r.date <= view.today]
    if records:
        last = records[-1]
        status.append(f"Last check-in: [{render.day_label(last.date)} ({last.tier})]({last.path.as_posix()})")
    else:
        status.append("Last check-in: none yet")
    flagged = view.open_flags()
    blocks = sum(1 for f in flagged if f["severity"] == "block")
    flag_text = f"{len(flagged)}" + (f" ({blocks} block)" if blocks else "") if flagged else "none"
    status.append(f"Open flags: {flag_text}")
    shown_zone = view.zone or timezone.utc
    status.append(f"Updated {render.day_label(view.as_of.astimezone(shown_zone).date())} "
                  f"{view.as_of.astimezone(shown_zone):%H:%M} ({view.config.athlete.timezone or 'UTC'})")
    status += [item.text for item in view.slot("dashboard.status")]
    lines = [header(paths.STATE.as_posix(), view.as_of), "# Training dashboard", ""]
    lines += _bullets(status[:STATUS_LIMIT]) + [""] + view.sessions_table()
    lines += ["", "## Progress", ""] + _bullets(_progress_summary(view))
    lines += ["", "## Links", ""] + _bullets(_links(records))
    return "\n".join(lines) + "\n"


def _progress_summary(view):
    found = []
    for exercise_id in view.program_order(view.series)[:SUMMARY_BESTS]:
        top = max(view.series[exercise_id], key=lambda p: (p["e1rm"], p["date"]))
        found.append(f"Best e1RM: {view.short_name(exercise_id)} {view.e1rm_text(exercise_id, top['e1rm'])} "
                     f"({_long_date(top['date'])})")
    if not found:
        found.append("No e1RM yet.")
    current, longest = view.streak
    found.append(f"Core-complete streak: {_weeks_text(current)} (longest {_weeks_text(longest)})")
    if view.body_weights:
        day, weight = view.body_weights[-1]
        found.append(f"Bodyweight: {_num(weight)} {view.config.athlete.bodyweight_units} on {_long_date(day)}, "
                     "scale (Hevy)")
    return found


def _weeks_text(count):
    return f"{count} week{'s' if count != 1 else ''}"


def _links(records):
    found = ["[This week's brief](this-week.md)", "[Progress](progress.md)"]
    if records:
        found.append(f"[Latest check-in]({records[-1].path.as_posix()})")
    found += [f"[Program]({paths.ROUTINE_PROGRAM_PAGE.as_posix()})",
              f"[All check-ins]({paths.CHECKINS_DIR.as_posix()}/)", f"[How this works]({TEMPLATE_README})"]
    return found


def render_progress(root, as_of, view=None):
    """`progress.md`: e1RM bests, part sections, the core-complete streak and bodyweight."""
    view = view or _View(root, as_of)
    lines = [header(paths.HISTORY_DIR.as_posix() + "/", view.as_of), "# Progress", "", "## Lifts", ""]
    lines += _lifts_table(view)
    for item in view.slot("progress.sections"):
        lines += ["", item.text.rstrip("\n")]
    current, longest = view.streak
    shown = view.weeks[-STREAK_WEEKS_SHOWN:]
    lines += ["", "## Core-complete weeks", "",
              f"Current streak: {_weeks_text(current)} · longest: {_weeks_text(longest)}", ""]
    if shown:
        marks = " ".join(NO_DATA if c is None else TRAINED if c else MISSED for _, c, _, _ in shown)
        lines.append(f"Last {_weeks_text(len(shown))} from the week of {_long_date(shown[0][0].start)}, "
                     f"oldest first: {marks}")
    else:
        lines.append("No finished week with an overlay yet.")
    lines += ["", "## Bodyweight", ""] + _bodyweight(view)
    return "\n".join(lines) + "\n"


def _lifts_table(view):
    notes = [f"{view.name(exercise_id)} ({observed[-1]['date']}): {stats.capacity_note(observed[-1])}."
             for exercise_id, observed in view.capacity["observations"].items() if not observed[-1]["comparable"]]
    if not view.series:
        return ["No comparable e1RM yet: model evidence is unavailable.", ""] + notes
    cutoff = (view.today - timedelta(days=CHANGE_DAYS)).isoformat()
    rows = [_row(["Lift", f"Best e1RM ({view.unit})", "Date", "Latest", f"{CHANGE_DAYS}-day change"]),
            "|---|---|---|---|---|"]
    for exercise_id, points in sorted(view.series.items(), key=lambda pair: view.name(pair[0])):
        best = max(points, key=lambda p: (p["e1rm"], p["date"]))
        latest = points[-1]
        before = [p for p in points if p["date"] <= cutoff]
        change = latest["e1rm"] - before[-1]["e1rm"] if before else None
        suffix = view.per_hand(exercise_id)
        rows.append(_row([view.name(exercise_id), _num(best["e1rm"]) + suffix, _long_date(best["date"]),
                          _num(latest["e1rm"]) + suffix, _signed(change)]))
    return rows + ([""] + notes if notes else [])


def _bodyweight(view):
    replaced = view.slot("progress.bodyweight")
    if replaced:
        return [item.text.rstrip("\n") for item in replaced]
    found = view.weekly_body_weights()[-BODYWEIGHT_WEEKS_SHOWN:]
    if not found:
        return ["No bodyweight source yet: weigh-ins logged in Hevy or a nutrition app show here."]
    unit = view.config.athlete.bodyweight_units
    lines = [_row(["Week of", f"Mean ({unit})"]), "|---|---|"]
    lines += [_row([_long_date(start), _num(mean)]) for start, mean in found]
    return lines + ["", "Source: scale (Hevy), weekly means of body measurements."]


RENDERERS = {BRIEF: render_brief, DASHBOARD: render_dashboard, PROGRESS: render_progress}


def render_all(root, now, kinds=KINDS, view=None):
    """{page path: text} for the pages, all rendered as of `now` from one read of the instance."""
    view = view or _View(root, now)
    return {PAGE_PATHS[kind]: RENDERERS[kind](root, view.as_of, view) for kind in kinds}


def brief_overlay(view):
    """The overlay the brief shows, as {id, approved}, or None when no overlay covers its week."""
    found = view.week_overlay
    return None if found is None else {"id": found["id"], "approved": overlay.is_approved(found)}


def readme_owner_problem(root):
    """Why `README.md` may not be overwritten (it exists and coach did not generate it), or None."""
    path = Path(root) / paths.DASHBOARD
    if path.is_file() and not is_generated(path.read_text(encoding="utf-8")):
        return ("README.md was not generated by coach (it has no generated-by header), so pages render will not "
                "overwrite it; run python3 -m coach pages render --replace-readme to make it the dashboard")
    return None


def write(root, now, kinds=KINDS, replace_readme=False, dry_run=False):
    """Render the pages and write them; refuses (exit 3) to replace a README coach did not generate."""
    root = Path(root)
    replaced = False
    if DASHBOARD in kinds:
        problem = readme_owner_problem(root)
        if problem and not replace_readme:
            raise RefusedError(problem)
        replaced = problem is not None
    view = _View(root, now)
    rendered = render_all(root, now, kinds, view)
    report = []
    for path, text in rendered.items():
        target = root / path
        before = target.read_text(encoding="utf-8") if target.is_file() else None
        if not dry_run:
            target.write_text(text, encoding="utf-8")
        report.append({"path": path, "changed": before != text, "written": not dry_run, "lines": text.count("\n")})
    return {"as_of": timestamp(as_of_moment(now)), "pages": report, "replaced_readme": replaced,
            "brief_overlay": brief_overlay(view), "dry_run": dry_run}


def freshness(root):
    """[(path, status, message)] for each page present: does it equal a fresh render at its own as-of time?"""
    root = Path(root)
    found = []
    for kind in KINDS:
        rel = PAGE_PATHS[kind]
        path = root / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        if kind == DASHBOARD and not is_generated(text):
            continue
        as_of = recorded_as_of(text)
        if as_of is None:
            found.append((rel, "fail", f"{rel} has no generated-by header with an as-of time; regenerate it with "
                                       f"python3 -m coach {RENDER_COMMAND}"))
            continue
        fresh = render_all(root, as_of, (kind,))[rel]
        if fresh != text:
            found.append((rel, "fail", f"{rel} differs from a fresh render as of {timestamp(as_of)} (hand-edited, or "
                                       f"its data changed); run python3 -m coach {RENDER_COMMAND}"))
        else:
            found.append((rel, "pass", f"{rel} matches a fresh render as of {timestamp(as_of)}"))
    return found


def publish_message(doc):
    return f"coach: publish week of {doc['span']['start']} ({doc['id']})"


def _git(root, *argv, env=None):
    return subprocess.run(["git", "-C", str(root), *argv], capture_output=True, text=True, env=env, timeout=120)


def _upstream(root, env):
    branch = _git(root, "symbolic-ref", "--quiet", "--short", "HEAD", env=env)
    if branch.returncode != 0:
        raise RefusedError("HEAD is not on a branch, so there is nothing to push; check out the instance's branch")
    name = branch.stdout.strip()
    remote = _git(root, "config", f"branch.{name}.remote", env=env).stdout.strip()
    merge = _git(root, "config", f"branch.{name}.merge", env=env).stdout.strip()
    if not remote or not merge:
        raise RefusedError(f"branch {name} has no upstream; set one with git push -u <remote> {name}, then publish")
    return name, remote, merge


def _ahead(root, env):
    """Commits on HEAD that the upstream's remote-tracking ref lacks, or None when that ref is unknown."""
    counted = _git(root, "rev-list", "--count", "@{upstream}..HEAD", env=env)
    return int(counted.stdout.strip()) if counted.returncode == 0 else None


def publish(root, overlay_id, now, record_date=None, dry_run=False, env=None):
    """Render and publish the pages, applicable session sheets, overlay and record (C38 publishing).

    Every refusal (exit 3) comes before anything is written. A rejected push exits 4 and keeps the commit.
    """
    root = Path(root)
    doc = overlay.load(root, overlay_id)
    if not overlay.is_approved(doc):
        raise RefusedError(f"overlay {overlay_id} is not approved (or was edited after approval); only an approved "
                           f"week is published: run python3 -m coach overlay approve {overlay_id} after the "
                           "athlete's go")
    found = checkin.records(root)
    if record_date is None:
        if not found:
            raise ValidationError("there is no check-in record to publish; write one with python3 -m coach checkin "
                                  "skeleton first")
        record = found[-1]
    else:
        day = dates.parse_date(str(record_date))
        record = next((r for r in found if r.date == day), None)
        if record is None:
            raise ValidationError(f"there is no check-in record check-ins/{day.isoformat()}.md")
    if shutil.which("git") is None:
        raise ConfigError("git is not installed, so the pages cannot be committed and pushed")
    if _git(root, "rev-parse", "--is-inside-work-tree", env=env).stdout.strip() != "true":
        raise RefusedError(f"{root} is not a git working tree, so there is nothing to publish to")
    branch, remote, merge = _upstream(root, env)
    publish_paths = [PAGE_PATHS[BRIEF], PAGE_PATHS[DASHBOARD], PAGE_PATHS[PROGRESS],
                     (paths.OVERLAYS_DIR / f"{overlay_id}.json").as_posix(), record.path.as_posix()]
    view = _View(root, now)
    include_sheets = not view.config.hevy.enabled
    if include_sheets:
        publish_paths.append(paths.SESSION_SHEETS.as_posix())
    staged = _git(root, "diff", "--cached", "--name-only", "-z", env=env).stdout.split("\0")
    others = sorted(p for p in staged if p and p not in publish_paths)
    if others:
        raise RefusedError("the git index already holds staged changes to other files, which a publish would "
                           f"sweep up: {', '.join(others)}; commit or unstage them first")
    problem = readme_owner_problem(root)
    if problem:
        raise RefusedError(problem)
    current_id = view.week_overlay["id"] if view.week_overlay else None
    if current_id != overlay_id:
        raise RefusedError(f"the brief shows overlay {current_id or 'none'}, not {overlay_id}; publish the approved "
                           "overlay in force for the brief's coming week")
    sheet_text = sheets.render_sheets(root, overlay_id) if include_sheets else None
    message = publish_message(doc)
    report = {"overlay_id": overlay_id, "record": record.path.as_posix(), "paths": publish_paths, "message": message,
              "branch": branch, "remote": remote, "upstream": merge, "commit": None, "pushed": False,
              "ahead": None, "dry_run": dry_run}
    if dry_run:
        return report
    report["rendered"] = write(root, now, KINDS)["pages"]
    if sheet_text is not None:
        (root / paths.SESSION_SHEETS).write_text(sheet_text, encoding="utf-8")
    checkin.skeleton(root, record.date, refresh=True, now=now)
    added = _git(root, "add", "--", *publish_paths, env=env)
    if added.returncode != 0:
        raise ValidationError(f"git add failed: {added.stderr.strip()}")
    if _git(root, "diff", "--cached", "--quiet", env=env).returncode == 0:
        report["ahead"] = _ahead(root, env)
        return report
    committed = _git(root, "commit", "-q", "-m", message, env=env)
    if committed.returncode != 0:
        raise ValidationError(f"git commit failed: {committed.stderr.strip() or committed.stdout.strip()}")
    report["commit"] = _git(root, "rev-parse", "HEAD", env=env).stdout.strip()
    push_env = dict(os.environ if env is None else env, GIT_TERMINAL_PROMPT="0")
    try:
        pushed = _git(root, "push", remote, f"HEAD:{merge}", env=push_env)
        reason = None if pushed.returncode == 0 else (pushed.stderr.strip().splitlines() or ["no output"])[-1]
    except subprocess.TimeoutExpired as exc:
        reason = f"no answer after {exc.timeout:g} s"
    report["ahead"] = _ahead(root, env)
    if reason is not None:
        raise NetworkError(f"git push to {remote} failed ({reason}); the commit {report['commit'][:12]} is kept: "
                           "push it by hand with git push", data=report)
    report["pushed"] = True
    return report
