"""The standing pages and publishing them (contract C38).

Three pages at the instance root, each rendered whole with the C11 header
and its as-of time: `this-week.md` (the brief), `README.md` (the
dashboard) and `progress.md`. History counts only up to the as-of time,
so a fresh render of an unchanged page is byte-identical; program, state,
overlays and records are read as they are now. Later items add content
through page parts (`coach.page_parts`). Loads print only through `_load`.
"""

