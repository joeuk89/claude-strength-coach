def guess_aisle(item):
    """Return (aisle, matched): matched is False when no keyword fitted and the default was used."""
    for aisle, words in _AISLE_KEYWORDS:
        for word in words:
            if re.search(rf"(?<![a-z]){re.escape(word)}(?![a-z])", item):
                return aisle, True
    return DEFAULT_AISLE_GUESS, False


def _plain_number(token):
    """A number with a decimal point: `1,000` is a thousand, `1,5` is one and a half."""
    if re.fullmatch(_THOUSANDS, token):
        return token.replace(",", "")
    return token.replace(",", ".")


def _qty_value(token):
    token = _plain_number(token.strip())
    total = 0.0
    for symbol, value in _FRACTIONS.items():
        if token.endswith(symbol):
            total += value
            token = token[:-1].strip()
    if not token:
        return total
    if " " in token:
        whole, fraction = token.split(None, 1)
        return total + float(whole) + _qty_value(fraction)
    if "/" in token:
        top, bottom = token.split("/")
        return total + float(top) / float(bottom)
    return total + float(token)


def _tidy_number(value):
    value = round(value, 3)
    return int(value) if float(value).is_integer() else value


def parse_ingredient(line):
    """Return {qty, unit, item} for one ingredient line, or None when it cannot be read exactly."""
    text = re.sub(r"\s+", " ", html_lib.unescape(line)).strip()
    text = re.sub(r"^[-*•]\s*", "", text)
    match = _QTY.match(text)
    if not match:
        return None
    qty = _qty_value(match.group(1))
    rest = text[match.end():].lstrip()
    if re.match(r"^(?:-|–|to\s)\s*\d", rest) or _MULTIPLIER.match(rest):
        return None
    unit, container = "each", None
    word = re.match(r"^([A-Za-z]+)\.?(?=\s|\(|$)", rest)
    if word and word.group(1).lower() in _UNITS:
        unit, factor = _UNITS[word.group(1).lower()]
        qty *= factor
        rest = rest[word.end():]
    elif word and word.group(1).lower() in _CONTAINERS:
        container = _CONTAINERS[word.group(1).lower()]
        rest = rest[word.end():]
    rest = re.sub(r"^\s*\([^)]*\)", "", rest).strip()
    rest = re.sub(r"^of\s+", "", rest)
    item = rest.lower().strip(" ,.;:")
    if not item or qty <= 0:
        return None
    if container:
        item = f"{item} {container}"
    return {"qty": _tidy_number(qty), "unit": unit, "item": item}


def ingredient_with_aisle(line):
    """Return (ingredient with a guessed aisle, matched) or (None, False)."""
    parsed = parse_ingredient(line)
    if parsed is None:
        return None, False
    aisle, matched = guess_aisle(parsed["item"])
    return {**parsed, "aisle": aisle}, matched


class _LdJsonScripts(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.blocks = []
        self._buffer = None

    def handle_starttag(self, tag, attrs):
        if tag == "script" and (dict(attrs).get("type") or "").strip().lower() == "application/ld+json":
            self._buffer = []

    def handle_endtag(self, tag):
        if tag == "script" and self._buffer is not None:
            self.blocks.append("".join(self._buffer))
            self._buffer = None

    def handle_data(self, data):
        if self._buffer is not None:
            self._buffer.append(data)


def _nodes(node):
    if isinstance(node, list):
        for item in node:
            yield from _nodes(item)
    elif isinstance(node, dict):
        yield node
        for key in ("@graph", "mainEntity"):
            if key in node:
                yield from _nodes(node[key])


def _is_recipe(node):
    kind = node.get("@type")
    return kind == "Recipe" or (isinstance(kind, list) and "Recipe" in kind)


def extract_recipe(page_html):
    """The first schema.org Recipe in the page's application/ld+json scripts, or None."""
    parser = _LdJsonScripts()
    parser.feed(page_html)
    parser.close()
    for block in parser.blocks:
        try:
            doc = json.loads(block.strip())
        except json.JSONDecodeError:
            continue
        for node in _nodes(doc):
            if _is_recipe(node):
                return node
    return None


def _clean(value):
    text = html_lib.unescape(re.sub(r"<[^>]+>", " ", str(value)))
    return re.sub(r"\s+", " ", text).strip()


_NUMBER = rf"(?:{_THOUSANDS}|{_DECIMAL})"


def _first_number(value):
    match = re.search(_NUMBER, str(value))
    return float(_plain_number(match.group(0))) if match else None


def _energy_kcal(value):
    text = str(value)
    kcal = re.search(rf"({_NUMBER})\s*(?:kcal|cal(?:orie)?s?)\b", text, re.I)
    if kcal:
        return float(_plain_number(kcal.group(1)))
    number = _first_number(text)
    if number is None:
        return None
    if re.search(r"kj\b", text, re.I) and not re.search(r"cal", text, re.I):
        return number / KJ_PER_KCAL
    return number


def _servings(value):
    values = value if isinstance(value, list) else [value]
    numbers = []
    for item in values:
        numbers += [int(n) for n in re.findall(r"\d+", str(item))]
    distinct = list(dict.fromkeys(n for n in numbers if n > 0))
    return (distinct[0] if distinct else None), len(distinct) > 1


def _iso_minutes(value):
    match = re.fullmatch(r"P(?:\d+D)?T?(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?", str(value or "").strip())
    if not match or not any(match.groups()):
        return None
    hours, minutes, _ = (int(group) if group else 0 for group in match.groups())
    return hours * 60 + minutes


_CATEGORY_SLOTS = (("breakfast", "breakfast"), ("brunch", "breakfast"), ("lunch", "lunch"), ("snack", "snack"),
                   ("dinner", "dinner"), ("main", "dinner"), ("supper", "dinner"))
_MEAL_KIT_HOSTS = {"gousto.co.uk": "gousto", "hellofresh": "hellofresh"}


def _slots_from(category):
    values = category if isinstance(category, list) else [category]
    found = []
    for value in values:
        text = str(value or "").lower()
        for word, slot in _CATEGORY_SLOTS:
            if word in text and slot not in found:
                found.append(slot)
    return found


def _steps(node):
    if isinstance(node, str):
        return [line for line in (_clean(part) for part in re.split(r"\n\s*\n|\r?\n", node)) if line]
    if isinstance(node, list):
        steps = []
        for item in node:
            steps += _steps(item)
        return steps
    if isinstance(node, dict):
        if "itemListElement" in node:
            return _steps(node["itemListElement"])
        text = node.get("text") or node.get("name")
        return [_clean(text)] if text and _clean(text) else []
    return []


def method_prose(recipe):
    steps = [step for step in _steps(recipe.get("recipeInstructions")) if step]
    if not steps:
        return ""
    return "## Method\n" + "\n".join(f"{n}. {step}" for n, step in enumerate(steps, 1)) + "\n"


def _grams(value):
    number = _first_number(value)
    if number is None:
        return None
    return _tidy_number(round(number, 1))


def import_jsonld(page_html, url=None):
    """Return (draft, flags) from a saved recipe page's schema.org JSON-LD; nothing is fetched."""
    recipe = extract_recipe(page_html)
    if recipe is None:
        raise ValidationError("the page has no schema.org Recipe in an application/ld+json script")
    flags = []
    title = _clean(recipe.get("name") or "") or "Untitled recipe"
    draft = {"schema_version": SCHEMA_VERSION, "title": title}

    slots = _slots_from(recipe.get("recipeCategory"))
    if not slots:
        slots = ["dinner"]
        flags.append({"code": "slot_guessed", "message": "the page names no meal slot; dinner is a guess"})
    draft["slots"] = slots

    servings, ambiguous = _servings(recipe.get("recipeYield"))
    if servings is None:
        servings = 1
        flags.append({"code": "servings_missing", "message": "the page gives no yield; servings = 1 is a guess"})
    draft["servings"] = servings
    draft["prep"] = "cook"
    total = _iso_minutes(recipe.get("totalTime"))
    if total is None:
        parts = [_iso_minutes(recipe.get(key)) for key in ("prepTime", "cookTime")]
        total = sum(p for p in parts if p) if any(parts) else None
    if total is None:
        flags.append({"code": "time_missing", "message": "the page gives no time; time_min = 0 until you set it"})
    draft["time_min"] = total or 0
    draft["status"] = "active"

    nutrition = recipe.get("nutrition") or {}
    macros = {
        "kcal": _energy_kcal(nutrition.get("calories")) if nutrition.get("calories") is not None else None,
        "protein_g": _grams(nutrition.get("proteinContent")),
        "carbs_g": _grams(nutrition.get("carbohydrateContent")),
        "fat_g": _grams(nutrition.get("fatContent")),
    }
    missing = [key for key, value in macros.items() if value is None]
    if missing:
        draft["nutrition"] = "estimated"
        flags.append({"code": "missing_nutrition",
                      "message": f"the page has no {', '.join(missing)}; estimate the macros from the ingredients",
                      "fields": missing})
    else:
        draft["nutrition"] = "published"

    source = url or recipe.get("url") or recipe.get("@id")
    if isinstance(source, str) and re.match(r"^https?://\S+$", source):
        draft["source"] = source
    host = urlparse(draft.get("source", "")).netloc.lower()
    provider = next((tag for key, tag in _MEAL_KIT_HOSTS.items() if key in host), None)
    draft["tags"] = ["meal-kit", provider] if provider else []

    if not missing:
        per_serving = dict(macros, kcal=round(macros["kcal"]))
        draft["per_serving"] = per_serving
        defaults = bank_defaults()
        status, computed, gap = macro_sum_status(
            per_serving, defaults["macro_sum_warn_pct"], defaults["macro_sum_fail_pct"]
        )
        if status != "pass":
            flags.append({"code": "macro_sum", "severity": status,
                          "message": f"published kcal {_num(per_serving['kcal'])} is {_pct(gap, per_serving['kcal'])} "
                                     f"off the macro sum {_num(computed)}"})
        serving_size = str(nutrition.get("servingSize") or "").lower()
        if ambiguous or per_serving["kcal"] > PER_SERVING_DOUBT_KCAL or "recipe" in serving_size:
            flags.append({"code": "per_serving_doubt",
                          "message": f"check the nutrition is per serving (yield {recipe.get('recipeYield')!r}, "
                                     f"{_num(per_serving['kcal'])} kcal)"})
    elif ambiguous:
        flags.append({"code": "per_serving_doubt", "message": f"the yield is ambiguous ({recipe.get('recipeYield')!r})"})

    ingredients, unparsed, guessed = [], [], []
    lines = recipe.get("recipeIngredient") or recipe.get("ingredients") or []
    for line in lines if isinstance(lines, list) else [lines]:
        text = _clean(line)
        ingredient, matched = ingredient_with_aisle(text)
        if ingredient is None:
            unparsed.append(text)
            continue
        ingredients.append(ingredient)
        if not matched:
            guessed.append(ingredient["item"])
    if ingredients:
        draft["ingredients"] = ingredients
    if unparsed:
        flags.append({"code": "unparsed_ingredients",
                      "message": f"{len(unparsed)} ingredient line(s) need an exact qty, unit and item",
                      "lines": unparsed})
    if guessed:
        flags.append({"code": "aisle_guessed", "message": f"no aisle keyword matched; {DEFAULT_AISLE_GUESS} is a guess",
                      "items": guessed})
    return draft, flags


def _yaml_scalar(raw):
    value = raw.strip()
    if value in ("", "null", "~"):
        return None
    if value in ("true", "false"):
        return value == "true"
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        return [_yaml_scalar(part) for part in inner.split(",")] if inner else []
    if len(value) > 1 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    if re.fullmatch(r"-?\d+\.\d+", value):
        return float(value)
    return value


def _strip_yaml_comment(line):
    quote = None
    for index, char in enumerate(line):
        if char in "'\"":
            quote = None if quote == char else (quote or char)
        elif char == "#" and quote is None and (index == 0 or line[index - 1] in " \t"):
            return line[:index]
    return line


def split_front_matter(text):
    """Return (meta, body, unread) for an old card whose text starts with `---`.

    Reads `key: value` lines and block lists (`key:` then `- item` lines); `unread` lists every other line.
    """
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].rstrip("\r\n") != "---":
        raise ValidationError("the card has no YAML front matter")
    meta, unread, offset, list_key = {}, [], len(lines[0]), None
    for line in lines[1:]:
        offset += len(line)
        bare = line.rstrip("\r\n")
        if bare == "---":
            return meta, text[offset:], unread
        content = _strip_yaml_comment(bare)
        if not content.strip():
            continue
        key = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):(.*)$", content)
        item = re.match(r"^\s*-\s+(.*)$", content)
        if key:
            value = _yaml_scalar(key.group(2))
            meta[key.group(1)] = value
            list_key = key.group(1) if value is None else None
        elif item and list_key:
            meta[list_key] = (meta[list_key] or []) + [_yaml_scalar(item.group(1))]
        else:
            unread.append(bare.strip())
            list_key = None
    raise ValidationError("the card's YAML front matter has no closing ---")


def _sections(body):
    """Split markdown into [(heading or None, chunk)] at `## ` lines, keeping every byte."""
    sections, heading, chunk = [], None, []
    for line in body.splitlines(keepends=True):
        if line.startswith("## "):
            sections.append((heading, "".join(chunk)))
            heading, chunk = line[3:].strip(), [line]
        else:
            chunk.append(line)
    sections.append((heading, "".join(chunk)))
    return [(h, c) for h, c in sections if h is not None or c]


_GENERATED_SECTIONS = ("ingredients", "variations")
_LEGACY_KEYS = ("name", "slot", "kcal", "protein", "carbs", "fat", "nutrition", "prep", "time", "servings", "source",
                "tags", "status")


def legacy_prose(text):
    """An old card's prose: every section but the title, stats table, Ingredients and Variations."""
    _, body, _ = split_front_matter(text)
    kept = []
    for heading, chunk in _sections(body):
        if heading is None:
            leftover = [line for line in chunk.splitlines(keepends=True)
                        if line.strip() and not line.startswith("# ") and not line.lstrip().startswith("|")]
            if leftover:
                kept.append("".join(leftover) + "\n")
        elif heading.lower() not in _GENERATED_SECTIONS:
            kept.append(chunk)
    return "".join(kept)


_VARIATION_LINE = re.compile(r"^\s*[-*]\s*\*\*(?P<name>[^*]+)\*\*\s*[—–-]+\s*(?P<rest>.*)$")
_DELTA_PART = re.compile(
    r"^(?P<sign>[+\-−])?\s*(?P<n>\d+(?:\.\d+)?)\s*(?:(?P<kcal>kcal|cal)|g\s*(?P<macro>protein|carbs?|carbohydrates?|fat|p|c|f))\b",
    re.I,
)
_MACRO_KEY = {"protein": "protein_g", "p": "protein_g", "carb": "carbs_g", "carbs": "carbs_g",
              "carbohydrate": "carbs_g", "carbohydrates": "carbs_g", "c": "carbs_g", "fat": "fat_g", "f": "fat_g"}


def _variation_from_line(line):
    match = _VARIATION_LINE.match(line)
    if not match:
        return None, None
    parts = [part.strip() for part in match.group("rest").split("·")]
    label_parts, delta, seen = [], {key: 0 for key in MACRO_KEYS}, set()
    for part in parts:
        found = _DELTA_PART.match(part)
        if not found:
            label_parts.append(part)
            continue
        value = float(found.group("n"))
        value = int(value) if value.is_integer() else value
        if found.group("sign") in ("-", "−"):
            value = -value
        key = "kcal" if found.group("kcal") else _MACRO_KEY[found.group("macro").lower()]
        delta[key] = value
        seen.add(key)
    name = re.sub(r"\s+", "-", match.group("name").strip().lower())
    note = None
    if "kcal" not in seen:
        delta["kcal"] = round(macro_kcal(delta))
        note = f'variation "{name}" states no kcal delta; {delta["kcal"]} is computed from its macros'
    label = " · ".join(p for p in label_parts if p) or name
    return {"name": name, "label": label, "changes": [], "delta": delta}, note


def convert_yaml_card(text, slug=None):
    """Return (draft, review_row) for an old YAML-front-matter card. Writes nothing."""
    meta, body, unread = split_front_matter(text)
    slug = meta.get("name") or slug
    title_match = re.search(r"^# (.+)$", body, re.M)
    title = title_match.group(1).strip() if title_match else str(slug).replace("-", " ").capitalize()
    slots = meta.get("slot") or []
    draft = {
        "schema_version": SCHEMA_VERSION,
        "title": title,
        "slots": slots if isinstance(slots, list) else [slots],
        "servings": meta.get("servings") or 1,
        "prep": meta.get("prep") or "cook",
        "time_min": meta.get("time") or 0,
        "status": meta.get("status") or "active",
        "nutrition": meta.get("nutrition") or "estimated",
    }
    if meta.get("source"):
        draft["source"] = meta["source"]
    if meta.get("tags"):
        draft["tags"] = meta["tags"]
    draft["per_serving"] = {
        "kcal": meta.get("kcal"), "protein_g": meta.get("protein"),
        "carbs_g": meta.get("carbs"), "fat_g": meta.get("fat"),
    }
    notes = [f"no {key} in the front matter" for key, value in draft["per_serving"].items() if value is None]
    notes += [f"front matter line not read: {line}" for line in unread]
    notes += [f"front matter key {key} is not carried over" for key in meta if key not in _LEGACY_KEYS]
    draft["per_serving"] = {k: (0 if v is None else v) for k, v in draft["per_serving"].items()}

    ingredients, unparsed, guessed_aisles, variations = [], [], [], []
    for heading, chunk in _sections(body):
        if heading is None:
            continue
        bullets = [line.strip() for line in chunk.splitlines()[1:] if re.match(r"^\s*[-*]\s", line)]
        if heading.lower() == "ingredients":
            for line in bullets:
                ingredient, matched = ingredient_with_aisle(line)
                if ingredient is None:
                    unparsed.append(re.sub(r"^[-*]\s*", "", line))
                    continue
                ingredients.append(ingredient)
                guessed_aisles.append({"item": ingredient["item"], "aisle": ingredient["aisle"], "matched": matched})
        elif heading.lower() == "variations":
            for line in bullets:
                variation, note = _variation_from_line(line)
                if variation is None:
                    notes.append(f"variation line not read: {line}")
                    continue
                variations.append(variation)
                if note:
                    notes.append(note)
    if ingredients:
        draft["ingredients"] = ingredients
    if variations:
        draft["variations"] = variations

    per_serving = draft["per_serving"]
    review = {
        "slug": slug,
        "title": title,
        "kcal": per_serving["kcal"],
        "protein_g": per_serving["protein_g"],
        "carbs_g": per_serving["carbs_g"],
        "fat_g": per_serving["fat_g"],
        "ingredients": len(ingredients),
        "unparsed": unparsed,
        "guessed_aisles": guessed_aisles,
        "variations": len(variations),
        "variations_to_fill": [v["name"] for v in variations if draft["prep"] != "eat-out"],
        "notes": notes,
    }
    return draft, review


def legacy_slot_notes(index_text, slots):
    """Return (notes, unplaced) from an old hand-kept index: the prose under each slot heading.

    `notes` maps a configured slot to its note; `unplaced` lists `{heading, note}` for prose under no
    heading or under one that names no configured slot. An index that coach rendered has neither.
    """
    if index_text.startswith("<!-- generated by coach"):
        return {}, []
    by_heading = {}
    for slot in slots:
        for name in (slot, f"{slot}s", _slot_heading(slot)):
            by_heading[name.lower()] = slot
    notes, unplaced = {}, []
    for heading, chunk in _sections(index_text):
        lines = chunk.splitlines()[1:] if heading is not None else chunk.splitlines()
        prose = [line.rstrip() for line in lines if not line.lstrip().startswith(("|", "# "))]
        note = "\n".join(prose).strip("\n")
        note = re.sub(r"\n{3,}", "\n\n", note)
        if not note:
            continue
        slot = by_heading.get((heading or "").strip().lower())
        if slot and slot not in notes:
            notes[slot] = note
        else:
            unplaced.append({"heading": heading, "note": note})
    return notes, unplaced


def slot_notes_toml(notes):
    if not notes:
        return ""
    lines = ["[nutrition.bank.slot_notes]"]
    lines += [f"{_toml_key(slot)} = {_toml_string(note)}" for slot, note in notes.items()]
    return "\n".join(lines) + "\n"


def review_table(rows, slot_notes=None, configured_notes=None):
    """The review table as markdown: one row per card, then the old index's slot notes."""
    lines = [
        "| Card | Title | kcal / P / C / F | Ingredients | Unparsed lines | Aisles to check | Variations to fill "
        "| Notes |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        aisles = ", ".join(f"{a['item']} → {a['aisle']}{'' if a['matched'] else ' (default)'}"
                           for a in row["guessed_aisles"]) or "—"
        lines.append(
            f"| {row['slug']} | {_cell(row['title'])} | {_num(row['kcal'])} / {_num(row['protein_g'])} / "
            f"{_num(row['carbs_g'])} / {_num(row['fat_g'])} | {row['ingredients']} | "
            f"{_cell('; '.join(row['unparsed'])) or '—'} | {_cell(aisles)} | "
            f"{', '.join(row['variations_to_fill']) or '—'} | {_cell('; '.join(row['notes'])) or '—'} |"
        )
    if slot_notes:
        configured_notes = configured_notes or {}
        lines += ["", "| Slot | Note in the old index | In config |", "| --- | --- | --- |"]
        for slot, note in slot_notes.items():
            in_config = "yes" if configured_notes.get(slot) == note else "no"
            cell = _cell(note).replace("\n", " ")
            lines.append(f"| {slot} | {cell} | {in_config} |")
    return "\n".join(lines) + "\n"
