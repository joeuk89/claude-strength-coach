def card_schema():
    global _schema
    if _schema is None:
        _schema = load_schema("recipe_card")
    return _schema


@dataclass
class Card:
    slug: str
    path: Path
    text: str
    data: dict
    body_start: int

    @property
    def rel(self):
        return (paths.MENU_DIR / f"{self.slug}.md").as_posix()

    @property
    def rest(self):
        return self.text[self.body_start:]


@dataclass
class Bank:
    cards: list = field(default_factory=list)
    broken: list = field(default_factory=list)

    def valid_cards(self):
        return [card for card in self.cards if not schema_errors(card.data)]

    def get(self, slug):
        return next((card for card in self.cards if card.slug == slug), None)


def read_text(path):
    return Path(path).read_text(encoding="utf-8")


def load_card(path):
    path = Path(path)
    if not SLUG.fullmatch(path.stem):
        raise ValidationError(f"{path}: a card's file name must be its slug, matching {SLUG.pattern}")
    data, rest = datablock.read(path, KIND)
    text = read_text(path)
    return Card(slug=path.stem, path=path, text=text, data=data, body_start=len(text) - len(rest))


def card_paths(root):
    menu = Path(root) / paths.MENU_DIR
    if not menu.is_dir():
        return []
    return sorted(p for p in menu.glob("*.md") if p.name != paths.MENU_INDEX.name)


def is_legacy(text):
    return text.startswith("---\n") or text.startswith("---\r\n")


def load_bank(root):
    bank = Bank()
    for path in card_paths(root):
        rel = (paths.MENU_DIR / path.name).as_posix()
        try:
            bank.cards.append(load_card(path))
        except ValidationError as exc:
            if is_legacy(read_text(path)):
                message = f"{rel} is an old YAML card; convert it with python3 -m coach recipes convert --parse"
                bank.broken.append((rel, message))
            else:
                bank.broken.append((rel, exc.message))
    return bank


def schema_errors(data):
    return validate(data, card_schema())


def bank_settings(config):
    nutrition = config.get("nutrition") if config is not None else None
    if nutrition and "bank" in nutrition:
        return nutrition["bank"]
    return bank_defaults()


def configured_slots(config):
    nutrition = (config.get("nutrition") if config is not None else None) or {}
    template = nutrition.get("template") or {}
    return list(template.get("slots") or DEFAULT_SLOTS)


def macro_kcal(macros):
    return (KCAL_PER_G_PROTEIN * macros["protein_g"] + KCAL_PER_G_CARBS * macros["carbs_g"]
            + KCAL_PER_G_FAT * macros["fat_g"])


def macro_sum_status(macros, warn_pct, fail_pct, floor_kcal=0):
    """Return (status, macro kcal, gap) comparing stated kcal with 4·P + 4·C + 9·F."""
    computed = macro_kcal(macros)
    gap = abs(macros["kcal"] - computed)
    base = abs(macros["kcal"])
    if gap > max(base * fail_pct / 100, floor_kcal):
        return "fail", computed, gap
    if gap > max(base * warn_pct / 100, floor_kcal):
        return "warn", computed, gap
    return "pass", computed, gap


def _num(value):
    if isinstance(value, float):
        value = round(value, 2)
        if value.is_integer():
            return str(int(value))
        return f"{value:.2f}".rstrip("0").rstrip(".")
    return str(value)


def _pct(gap, stated):
    return f"{round(gap / stated * 100)}%" if stated else "all"


def validate_card(card, config):
    """Every problem with one card, as check Results; an empty list means it passes."""
    results = []

    def fail(message):
        results.append(Result("fail", f"{card.slug}: {message}", card.rel))

    def warn(message):
        results.append(Result("warn", f"{card.slug}: {message}", card.rel))

    errors = schema_errors(card.data)
    if errors:
        for error in errors:
            fail(f"{error.path} {error.message}")
        return results

    data = card.data
    bank = bank_settings(config)
    slots = configured_slots(config)
    aisles = list(bank["aisles"])

    for slot in data["slots"]:
        if slot not in slots:
            fail(f'slot "{slot}" is not a configured slot ({", ".join(slots)})')
    if len(set(data["slots"])) != len(data["slots"]):
        fail("slots lists a slot twice")

    per_serving = data["per_serving"]
    status, computed, gap = macro_sum_status(per_serving, bank["macro_sum_warn_pct"], bank["macro_sum_fail_pct"])
    if status != "pass":
        limit = bank[f"macro_sum_{status}_pct"]
        message = (f"kcal {_num(per_serving['kcal'])} is {_pct(gap, per_serving['kcal'])} off the macro sum "
                   f"{_num(computed)} (4 x protein + 4 x carbs + 9 x fat); {status} above {_num(limit)}%")
        (fail if status == "fail" else warn)(message)

    if per_serving["kcal"] > 0:
        density = per_serving["protein_g"] / per_serving["kcal"] * 100
        minimums = bank["min_protein_per_100kcal"]
        for slot in data["slots"]:
            minimum = minimums.get(slot, 0)
            if minimum and density < minimum:
                warn(f"{density:.1f} g protein per 100 kcal is under the {slot} minimum of {_num(minimum)} "
                     "(min_protein_per_100kcal, a heuristic)")

    ingredients = data.get("ingredients", [])
    if data["prep"] == "eat-out" and ingredients:
        fail('a prep = "eat-out" card has no ingredients; say what to order in the prose')
    elif data["prep"] != "eat-out" and not ingredients:
        fail('needs at least one ingredient (only prep = "eat-out" cards have none)')

    by_item = {}
    for ingredient in ingredients:
        item = ingredient["item"]
        if item in by_item:
            fail(f'ingredient "{item}" is listed twice')
        by_item[item] = ingredient
        if ingredient["aisle"] not in aisles:
            warn(f'ingredient "{item}" has aisle "{ingredient["aisle"]}", not one of [nutrition.bank] aisles')

    names = set()
    for variation in data.get("variations", []):
        _validate_variation(variation, by_item, aisles, bank, data["prep"], names, fail, warn)
    return results


def _validate_variation(variation, by_item, aisles, bank, prep, names, fail, warn):
    name = variation["name"]
    label = f'variation "{name}"'
    if name in names:
        fail(f"{label} is defined twice")
    names.add(name)

    changed = set()
    for change in variation["changes"]:
        item = change["item"]
        if item in changed:
            fail(f'{label} changes "{item}" twice')
        changed.add(item)
        base = by_item.get(item)
        if base is not None:
            if change["unit"] != base["unit"]:
                fail(f'{label} changes "{item}" in {change["unit"]}, but the card lists it in {base["unit"]}')
            elif base["qty"] + change["qty"] < 0:
                fail(f'{label} takes {_num(-change["qty"])} {change["unit"]} of "{item}" from a card that has '
                     f'{_num(base["qty"])}')
            if change["qty"] == 0:
                warn(f'{label} changes "{item}" by 0')
        elif change["qty"] <= 0:
            fail(f'{label} reduces "{item}", which is not an ingredient of the card')
        elif "aisle" not in change:
            fail(f'{label} adds "{item}" without an aisle')
        elif change["aisle"] not in aisles:
            warn(f'{label} adds "{item}" with aisle "{change["aisle"]}", not one of [nutrition.bank] aisles')
    if not variation["changes"] and prep != "eat-out":
        warn(f"{label} changes no ingredients, so shopping lists ignore it")

    delta = variation["delta"]
    status, computed, gap = macro_sum_status(
        delta, bank["macro_sum_warn_pct"], bank["macro_sum_fail_pct"], VARIATION_KCAL_FLOOR
    )
    if status != "pass":
        limit = bank[f"macro_sum_{status}_pct"]
        message = (f"{label}: delta kcal {_num(delta['kcal'])} is {_num(gap)} kcal off its macro sum "
                   f"{_num(computed)}; {status} above {_num(limit)}% or {VARIATION_KCAL_FLOOR} kcal")
        (fail if status == "fail" else warn)(message)


def region_markers(slug):
    return render.begin_marker(KIND, slug), render.end_marker(KIND, slug)


def _signed(value):
    text = _num(abs(value))
    return f"+{text}" if value > 0 else f"{_MINUS}{text}"


def _delta_text(delta):
    parts = []
    for key, unit in (("kcal", " kcal"), ("protein_g", " g P"), ("carbs_g", " g C"), ("fat_g", " g F")):
        if delta[key]:
            parts.append(f"{_signed(delta[key])}{unit}")
    return "".join(f" · {part}" for part in parts)


def ingredient_text(ingredient):
    qty = _num(ingredient["qty"])
    if ingredient["unit"] == "each":
        return f"{qty} {ingredient['item']}"
    return f"{qty} {ingredient['unit']} {ingredient['item']}"


def _cell(text):
    return str(text).replace("|", "\\|")


def render_card_region(card):
    """The card's rendered region, from the start of its begin marker to the end of its end marker."""
    data = card.data
    per_serving = data["per_serving"]
    begin, end = region_markers(card.slug)
    lines = [
        begin,
        f"# {data['title']}",
        "",
        "| | |",
        "| --- | --- |",
        f"| **Per serving** | {_num(per_serving['kcal'])} kcal · {_num(per_serving['protein_g'])} g P · "
        f"{_num(per_serving['carbs_g'])} g C · {_num(per_serving['fat_g'])} g F |",
        f"| **Slot** | {', '.join(data['slots'])} |",
        f"| **Prep** | {data['prep']} · {data['time_min']} min · serves {data['servings']} |",
        f"| **Nutrition** | {data['nutrition']} |",
    ]
    if data.get("source"):
        lines.append(f"| **Source** | [link]({_cell(data['source'])}) |")
    if data.get("tags"):
        lines.append(f"| **Tags** | {', '.join(data['tags'])} |")
    lines.append(f"| **Status** | {data['status']} |")
    if data.get("ingredients"):
        lines += ["", "## Ingredients"] + [f"- {ingredient_text(item)}" for item in data["ingredients"]]
    if data.get("variations"):
        lines += ["", "## Variations"]
        lines += [f"- **{v['name']}** — {v['label']}{_delta_text(v['delta'])}" for v in data["variations"]]
    lines.append(end)
    return "\n".join(lines)


def find_region(card):
    """Return (start, stop) of the card's region in its text, or None when it has none."""
    try:
        regions = render.find_regions(card.rest, KIND)
    except ValueError as exc:
        raise ValidationError(f"{card.rel}: {exc}") from None
    for region_id, _, _ in regions:
        if region_id != card.slug:
            raise ValidationError(f'{card.rel}: its region is marked for card "{region_id}", not "{card.slug}"')
    if len(regions) > 1:
        raise ValidationError(f"{card.rel}: the region appears {len(regions)} times")
    if not regions:
        return None
    _, start, stop = regions[0]
    return card.body_start + start, card.body_start + stop


def current_region(card):
    span = find_region(card)
    return None if span is None else card.text[span[0]:span[1]]


def rendered_text(card):
    """The card's whole text with its region rendered fresh; the data block and prose keep their bytes."""
    region = render_card_region(card)
    span = find_region(card)
    if span is None:
        rest = card.rest
        gap = "" if not rest or rest.startswith(("\n", "\r\n")) else "\n"
        return card.text[:card.body_start] + region + "\n" + gap + rest
    return card.text[:span[0]] + region + card.text[span[1]:]


def _slot_heading(slot):
    return _SLOT_HEADINGS.get(slot, slot.replace("-", " ").capitalize())


def _link_text(title):
    return title.replace("|", "\\|").replace("[", "\\[").replace("]", "\\]")


def render_index(bank, config):
    """The whole of `nutrition/menu/index.md`: one section per configured slot, benched cards last."""
    notes = bank_settings(config)["slot_notes"]
    cards = bank.valid_cards()
    lines = [INDEX_HEADER, "# Recipe bank", ""]
    for slot in configured_slots(config):
        lines += [f"## {_slot_heading(slot)}", ""]
        if notes.get(slot):
            lines += [notes[slot], ""]
        rows = sorted(
            (card for card in cards if slot in card.data["slots"]),
            key=lambda card: (card.data["status"] != "active", card.data["title"].lower(), card.slug),
        )
        if not rows:
            lines += ["_No cards yet._", ""]
            continue
        lines += ["| Recipe | kcal | Protein | Prep | Time | Status |", "| --- | --- | --- | --- | --- | --- |"]
        for card in rows:
            data = card.data
            lines.append(
                f"| [{_link_text(data['title'])}]({card.slug}.md) | {_num(data['per_serving']['kcal'])} | "
                f"{_num(data['per_serving']['protein_g'])} g | {data['prep']} | {data['time_min']} min | "
                f"{data['status']} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


_BARE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")
_ESCAPES = {"\\": "\\\\", '"': '\\"', "\b": "\\b", "\t": "\\t", "\n": "\\n", "\f": "\\f", "\r": "\\r"}


def _toml_string(text):
    out = []
    for char in text:
        if char in _ESCAPES:
            out.append(_ESCAPES[char])
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append(f"\\u{ord(char):04X}")
        else:
            out.append(char)
    return '"' + "".join(out).replace("-->", "--\\u003E") + '"'


def _toml_key(key):
    return key if _BARE_KEY.fullmatch(key) else _toml_string(key)


def _toml_value(value, where):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError(f"{where}: {value} cannot be written as TOML")
        return repr(value)
    if isinstance(value, str):
        return _toml_string(value)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(item, f"{where}[{i}]") for i, item in enumerate(value)) + "]"
    if isinstance(value, dict):
        pairs = (f"{_toml_key(k)} = {_toml_value(v, f'{where}.{k}')}" for k, v in value.items())
        return "{" + ", ".join(pairs) + "}"
    raise ValueError(f"{where}: {value!r} cannot be written as TOML (a card has no nulls)")


def _is_table_list(value):
    return isinstance(value, list) and value and all(isinstance(item, dict) for item in value)


def card_toml(draft):
    """The TOML text of a card's data block; `tomllib.loads` of it equals `draft`."""
    order = [k for k in _TOP_ORDER if k in draft] + sorted(k for k in draft if k not in _TOP_ORDER)
    scalars = [k for k in order if not isinstance(draft[k], dict) and not _is_table_list(draft[k])]
    tables = [k for k in order if isinstance(draft[k], dict)]
    table_lists = [k for k in order if _is_table_list(draft[k])]
    lines = [f"{_toml_key(k)} = {_toml_value(draft[k], k)}" for k in scalars]
    for key in tables:
        lines += ["", f"[{_toml_key(key)}]"]
        lines += [f"{_toml_key(k)} = {_toml_value(v, f'{key}.{k}')}" for k, v in draft[key].items()]
    for key in table_lists:
        for index, entry in enumerate(draft[key]):
            lines += ["", f"[[{_toml_key(key)}]]"]
            lines += [f"{_toml_key(k)} = {_toml_value(v, f'{key}[{index}].{k}')}" for k, v in entry.items()]
    return "\n".join(lines) + "\n"


def compose_card(slug, draft, prose=""):
    """A whole card file: data block, fresh region, then the prose."""
    block = f"<!-- coach:{KIND}\n{card_toml(draft)}{datablock.CLOSER}\n"
    card = Card(slug=slug, path=paths.MENU_DIR / f"{slug}.md", text=block, data=draft, body_start=len(block))
    text = block + render_card_region(card) + "\n"
    prose = prose.strip("\r\n")
    return text + "\n" + prose + "\n" if prose else text


def suggest_slug(title):
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return slug[:60].rstrip("-") or "recipe"


