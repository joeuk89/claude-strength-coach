"""Session sheets: the week's overlay as per-set tables to train from without Hevy (contract C46, C11).

`this-week-sheets.md` is rendered whole from one overlay: the brief's (the
latest created of those in force in the week holding tomorrow), else the
next to start. Loads print without the Hevy value. A fresh render of an
unchanged overlay is byte-identical, so the file goes stale only when its
overlay changes or someone edits it.
"""

import os
import re
import tempfile
from datetime import timedelta
from pathlib import Path

from coach import config as config_module
from coach import dates, overlay, paths, render, units
from coach.errors import ValidationError
from coach.library import Library

COMMAND = "sheets render"
HEADER = re.compile(r"^<!-- generated by coach from (\S+); edit the data, then run: "
                    r"python3 -m coach sheets render -->$")
COLUMNS = ("Exercise", "Sets × reps", "Load", "RPE", "Rest", "Done")
HOW_TO_LOG = ('To log a session, reply to the coach with what you did: the reps of every set with a range or a +, '
              'the load you used where it says "choose the load", how hard each exercise felt (RPE) if you can say, '
              'and anything else that differed. "As written" covers fixed reps and loads only ("squat as written, '
              'RPE 8; bench 10, 9, 8 at RPE 9").')
REP_OUT = ("A + set (5+) asks for at least those reps, then as many more as you can until the next rep would pass "
           "its RPE stop; it is not a set to failure. Log the reps you did.")
_SET_LABELS = {"warmup": "warm-up", "dropset": "drop set", "failure": "to failure"}


def label():
    return paths.SESSION_SHEETS.as_posix()


def source_path(overlay_id):
    return (paths.OVERLAYS_DIR / f"{overlay_id}.json").as_posix()


def header(overlay_id):
    return (f"<!-- generated by coach from {source_path(overlay_id)}; edit the data, then run: "
            f"python3 -m coach {COMMAND} -->")


def _latest(docs):
    return max(docs, key=lambda d: (dates.parse_timestamp(d["created_at"]), d["id"]), default=None)


def current(docs, today, week_starts):
    """The overlay the sheets show: the brief's week overlay, else the next to start, else None."""
    week = dates.week_span(today + timedelta(days=1), week_starts)
    in_week = [hit[0] for hit in (overlay.pick_in_force(docs, day) for day in week.days()) if hit]
    if in_week:
        return _latest(in_week)
    later = [d for d in docs if d["span"]["start"] > today.isoformat()]
    if not later:
        return None
    first = min(d["span"]["start"] for d in later)
    return _latest([d for d in later if d["span"]["start"] == first])


def anchors(doc):
    """(session, anchor) in date order; a session id seen again gets `-2`, `-3`."""
    seen, found = {}, []
    for session in sorted(doc["sessions"], key=lambda s: s["date"]):
        count = seen.get(session["session_id"], 0) + 1
        seen[session["session_id"]] = count
        found.append((session, session["session_id"] if count == 1 else f"{session['session_id']}-{count}"))
    return found


def _number(value):
    return str(units.json_number(value))


def _reps(set_):
    if set_.get("rep_range") is not None:
        return units.rep_range_text(set_['rep_range']['start'], set_['rep_range']['end'])
    if set_.get("reps") is not None:
        return _number(set_["reps"]) + ("+" if set_.get("rep_out") else "")
    if set_.get("duration_seconds") is not None:
        return f"{_number(set_['duration_seconds'])} s"
    if set_.get("distance_meters") is not None:
        return f"{_number(set_['distance_meters'])} m"
    return "?"


def _load(line, set_):
    load = set_.get("load")
    if load is not None:
        return units.format_load(load, show_hevy=False)
    return render.CHOOSE_THE_LOAD if line["load_mode"] in units.LOADED_MODES else "—"


def _cell(value):
    return "" if value is None else str(value).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def _row(cells):
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _rows(line, name):
    """Warm-ups on their own rows, then each run of equal working sets; the name on the first row only."""
    groups = []
    for set_ in line["sets"]:
        key = (set_.get("type"), _reps(set_), _load(line, set_), render.rpe_cell(set_))
        if groups and groups[-1][0] == key:
            groups[-1][1] += 1
        else:
            groups.append([key, 1])
    rows, rest_shown = [], False
    for index, ((kind, reps, load, rpe), count) in enumerate(groups):
        sets = f"{count}×{reps}" + (f" {_SET_LABELS[kind]}" if kind in _SET_LABELS else "")
        rest = ""
        if kind != "warmup" and not rest_shown and line.get("rest_seconds") is not None:
            rest, rest_shown = f"{line['rest_seconds']} s", True
        rows.append(_row([name if index == 0 else "", sets, load, rpe, rest, ""]))
    return rows


def _notes(line, name):
    parts = []
    if line.get("focus"):
        parts.append(f"Focus: {line['focus']}")
    if line.get("cues"):
        parts.append(f"Cues: {line['cues']}")
    return f"- **{name}**: " + " · ".join(parts) if parts else None


def render_sheets(root, overlay_id):
    """The whole sheets file for one overlay."""
    doc = overlay.load(root, overlay_id)
    library = Library.load(root)

    def name(exercise_id):
        entry = library.get(exercise_id)
        return entry["name"] if entry else exercise_id

    span = doc["span"]
    unit = config_module.load(root).athlete.units
    lines = [header(doc["id"]), f"# Session sheets · week of {render.short_date(span['start'])}", "",
             f"Overlay `{doc['id']}` ({doc['kind'].replace('_', ' ')}) · {render.day_label(span['start'])} – "
             f"{render.day_label(span['end'])} · loads in {unit}"]
    if not overlay.is_approved(doc):
        lines.append("Not approved yet: train from these once the week is agreed.")
    lines += ["", f"**Week focus:** {doc['focus']}"]
    for session, anchor in anchors(doc):
        lines += ["", f'<a id="{anchor}"></a>', "", f"## {session['title']} · {render.day_label(session['date'])}", ""]
        if session.get("location"):
            lines += [f"Location: {session['location']}", ""]
        if session.get("focus"):
            lines += [f"Focus: {session['focus']}", ""]
        lines += [_row(COLUMNS), "|" + "---|" * len(COLUMNS)]
        for line in session["exercises"]:
            lines += _rows(line, name(line["exercise_id"]))
        notes = [n for n in (_notes(line, name(line["exercise_id"])) for line in session["exercises"]) if n]
        if notes:
            lines += [""] + notes
    lines += ["", "---", ""]
    if any(set_.get("rep_out") for session in doc["sessions"] for line in session["exercises"]
           for set_ in line["sets"]):
        lines += [REP_OUT, ""]
    lines.append(HOW_TO_LOG)
    return "\n".join(lines) + "\n"


def write(root, today, overlay_id=None, dry_run=False):
    """Render the sheets for `overlay_id`, or the current overlay, into `this-week-sheets.md`."""
    root = Path(root)
    if overlay_id is None:
        config = config_module.load(root)
        doc = current(overlay.list(root), today, config.athlete.week_starts)
        if doc is None:
            raise ValidationError("No overlay covers the coming week or starts later; build and approve one first")
        overlay_id = doc["id"]
    text = render_sheets(root, overlay_id)
    target = root / paths.SESSION_SHEETS
    changed = not target.is_file() or target.read_text(encoding="utf-8") != text
    if changed and not dry_run:
        _write_text(target, text)
    doc = overlay.load(root, overlay_id)
    return {"path": label(), "overlay_id": overlay_id, "approved": overlay.is_approved(doc),
            "sessions": [{"session_id": s["session_id"], "date": s["date"], "anchor": a} for s, a in anchors(doc)],
            "changed": changed, "written": changed and not dry_run, "dry_run": dry_run}


def _write_text(target, text):
    fd, temp = tempfile.mkstemp(prefix=f".{target.name}.", suffix=".tmp", dir=target.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.replace(temp, target)
    except BaseException:
        if os.path.exists(temp):
            os.unlink(temp)
        raise


def freshness(root, today):
    """(status, message) results for `sheets_render_fresh`."""
    root = Path(root)
    target = root / paths.SESSION_SHEETS
    config = config_module.load(root)
    try:
        docs = overlay.list(root)
    except ValidationError as exc:
        return [("skip", f"cannot read the overlays: {exc.message}")]
    now_doc = current(docs, today, config.athlete.week_starts)
    if not target.is_file():
        if now_doc is None:
            return [("skip", "No session sheets and no overlay to render them from.")]
        return [("warn", f"No session sheets yet for overlay {now_doc['id']}; run python3 -m coach {COMMAND}.")]
    text = target.read_text(encoding="utf-8")
    match = HEADER.match(text.split("\n", 1)[0])
    if not match:
        return [("fail", f"{label()} has no coach header, so it was not rendered by coach; run python3 -m coach "
                         f"{COMMAND}.")]
    overlay_id = Path(match.group(1)).stem
    try:
        fresh = render_sheets(root, overlay_id)
    except ValidationError as exc:
        return [("fail", f"{label()} cannot be rendered again from {match.group(1)}: {exc.message}")]
    results = []
    if text != fresh:
        results.append(("fail", f"{label()} differs from a fresh render of overlay {overlay_id}; it was edited by "
                                f"hand or the overlay changed. Run python3 -m coach {COMMAND}."))
    if now_doc is not None and now_doc["id"] != overlay_id:
        results.append(("warn", f"{label()} shows overlay {overlay_id}, but the coming week's overlay is "
                                f"{now_doc['id']}; run python3 -m coach {COMMAND}."))
    return results or [("pass", f"{label()} matches a fresh render of overlay {overlay_id}.")]
