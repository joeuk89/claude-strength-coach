"""Session sheets, their freshness check and the brief's link to them (contract C46, C11, C38, C5)."""

import copy
import re
import unittest
from datetime import date, datetime, timezone

from coach import pages, sheets
from tests.support import INSTANCES, VALID, run_cli
from tests.test_manual_log import NoHevyCase

SUNDAY = "2026-10-11T18:00:00Z"
WEEKLY = "2026-10-12-weekly"
SHEETS = "this-week-sheets.md"
HEADER = re.compile(r"^<!-- generated by coach from (\S+); edit the data, then run: "
                    r"python3 -m coach sheets render -->$")


def check(root, expect=0, now=SUNDAY):
    code, envelope, stderr = run_cli(["--root", str(root), "check", "--only", "sheets_render_fresh"],
                                     env={"COACH_NOW": now})
    assert code == expect, (code, envelope, stderr)
    return envelope["data"]["results"]


class SheetsRenderTest(NoHevyCase):
    now = SUNDAY

    def setUp(self):
        super().setUp()
        (self.root / SHEETS).unlink()

    def render(self, *extra, expect=0):
        return self.coach("sheets", "render", *extra, expect=expect)

    def text(self):
        return (self.root / SHEETS).read_text(encoding="utf-8")

    def test_writes_the_sheets_with_the_c11_header_and_a_section_per_session(self):
        data = self.render()["data"]
        self.assertEqual((data["overlay_id"], data["written"]), (WEEKLY, True))
        text = self.text()
        match = HEADER.match(text.splitlines()[0])
        self.assertIsNotNone(match, text.splitlines()[0])
        self.assertEqual(match.group(1), f"data/overlays/{WEEKLY}.json")
        self.assertIn('<a id="session-a"></a>', text)
        self.assertIn('<a id="session-b"></a>', text)
        self.assertLess(text.index("## Session A · Mon 12 Oct"), text.index("## Session B · Thu 15 Oct"))

    def test_db_bench_prints_per_hand_only(self):
        self.render()
        text = self.text()
        self.assertIn("| Bench Press (Dumbbell) | 1×10 warm-up | 12.5/hand |", text)
        self.assertIn("|  | 3×8–10 | 25/hand | 8 | 120 s |  |", text)
        self.assertNotIn("Hevy", text)

    def test_every_exercise_has_sets_load_rpe_rest_cues_and_an_empty_done_column(self):
        self.render()
        text = self.text()
        self.assertEqual(text.count("| Exercise | Sets × reps | Load | RPE | Rest | Done |"), 2)
        self.assertIn("|  | 3×5 | 100 | 7 | 180 s |  |", text)
        self.assertIn("| Pull Up | 3×8 | BW | 8 | 120 s |  |", text)
        self.assertIn("- **Back Squat (Barbell)**: Cues: brace · knees out", text)
        self.assertIn("Focus: pause 1 s on the chest", text)
        self.assertIn("reply to the coach with what you did: the reps of every set with a range", text)
        self.assertIn('the load you used where it says "choose the load"', text)
        self.assertIn("how hard each exercise felt (RPE) if you can say", text)
        self.assertIn('"As written" covers fixed reps and loads only', text)
        self.assertNotIn("differences only", text)

    def test_a_second_run_is_byte_identical(self):
        self.render()
        before = (self.root / SHEETS).read_bytes()
        data = self.render()["data"]
        self.assertFalse(data["changed"])
        self.assertEqual((self.root / SHEETS).read_bytes(), before)

    def test_dry_run_writes_nothing(self):
        data = self.render("--dry-run")["data"]
        self.assertTrue(data["changed"])
        self.assertFalse((self.root / SHEETS).exists())

    def test_a_one_character_edit_fails_the_check(self):
        self.render()
        self.assertEqual([r["status"] for r in check(self.root)], ["pass"])
        text = self.text().replace("| 25/hand | 8 |", "| 26/hand | 8 |", 1)
        (self.root / SHEETS).write_text(text, encoding="utf-8")
        results = check(self.root, expect=1)
        self.assertEqual([r["status"] for r in results], ["fail"])
        self.assertEqual(results[0]["path"], SHEETS)

    def test_no_sheets_warns_and_hevy_on_skips(self):
        self.assertEqual([r["status"] for r in check(self.root)], ["warn"])
        self.assertEqual([r["status"] for r in check(VALID)], ["skip"])

    def test_an_unknown_overlay_exits_1(self):
        self.render("--overlay", "2026-11-30-weekly", expect=1)

    def test_an_unapproved_overlay_renders_with_a_warning(self):
        path = self.root / "data" / "overlays" / f"{WEEKLY}.json"
        path.write_text(path.read_text(encoding="utf-8").replace('"focus": "Heavier', '"focus": "Lighter'),
                        encoding="utf-8")
        envelope = self.render()
        self.assertFalse(envelope["data"]["approved"])
        self.assertTrue(any("not approved" in w for w in envelope["warnings"]))
        self.assertIn("Not approved yet", self.text())


