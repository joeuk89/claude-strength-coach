def _doc(overlay_id, start, end, created, sessions):
    return {"id": overlay_id, "created_at": created, "span": {"start": start, "end": end},
            "sessions": [{"session_id": s, "date": d, "title": s.title()} for s, d in sessions]}


class WhichOverlayTest(unittest.TestCase):
    """The sheets show the brief's overlay: the week holding tomorrow, else the next to start."""

    this_week = _doc("2026-10-12-weekly", "2026-10-12", "2026-10-18", "2026-10-11T18:00:00Z",
                     [("session-a", "2026-10-12"), ("session-b", "2026-10-15")])
    next_week = _doc("2026-10-19-weekly", "2026-10-19", "2026-10-25", "2026-10-18T18:00:00Z",
                     [("session-a", "2026-10-19")])

    def test_midweek_shows_this_weeks_overlay(self):
        found = sheets.current([self.this_week, self.next_week], date(2026, 10, 14), "monday")
        self.assertEqual(found["id"], "2026-10-12-weekly")

    def test_on_sunday_after_programming_it_shows_next_week(self):
        found = sheets.current([self.this_week, self.next_week], date(2026, 10, 18), "monday")
        self.assertEqual(found["id"], "2026-10-19-weekly")

    def test_a_sunday_week_start_repeats_the_rule(self):
        found = sheets.current([self.this_week, self.next_week], date(2026, 10, 17), "sunday")
        self.assertEqual(found["id"], "2026-10-19-weekly")

    def test_with_a_gap_it_shows_the_next_to_start(self):
        found = sheets.current([self.next_week], date(2026, 10, 5), "monday")
        self.assertEqual(found["id"], "2026-10-19-weekly")
        self.assertIsNone(sheets.current([self.this_week], date(2026, 11, 1), "monday"))

    def test_a_session_seen_twice_gets_a_numbered_anchor(self):
        doc = copy.deepcopy(self.this_week)
        doc["sessions"].append({"session_id": "session-a", "date": "2026-10-17", "title": "Session A"})
        self.assertEqual([a for _, a in sheets.anchors(doc)], ["session-a", "session-b", "session-a-2"])


class BriefLinkTest(unittest.TestCase):
    as_of = datetime(2026, 10, 11, 18, 0, tzinfo=timezone.utc)

    def after_sessions_table(self, root):
        lines = pages.render_brief(root, self.as_of).splitlines()
        start = lines.index("## Sessions") + 1
        end = next(i for i in range(start, len(lines)) if lines[i].startswith("## "))
        table_end = max(i for i in range(start, end) if lines[i].startswith("|"))
        return [line for line in lines[table_end + 1:end] if line.strip()]

    def test_hevy_off_adds_exactly_one_line_linking_the_sheets(self):
        footer = self.after_sessions_table(INSTANCES / "nohevy")
        self.assertEqual(len(footer), 1, footer)
        self.assertIn(f"]({SHEETS})", footer[0])
        self.assertIn(f"({SHEETS}#session-a)", footer[0])

    def test_hevy_on_has_no_sheets_line(self):
        self.assertEqual(self.after_sessions_table(VALID), [])

    def test_the_brief_prints_dumbbell_loads_without_the_hevy_value_when_hevy_is_off(self):
        nohevy = pages.render_brief(INSTANCES / "nohevy", self.as_of)
        self.assertIn("- Bench Press 22.5 → 25/hand\n", nohevy)
        self.assertIn("| Single Arm Row 3×10 @ 30 |", nohevy)
        self.assertNotIn("(Hevy:", nohevy)
        hevy = pages.render_brief(VALID, self.as_of)
        self.assertIn("- Bench Press 22.5 → 25/hand (Hevy: 50)\n", hevy)
        self.assertIn("| Single Arm Row 3×10 @ 30 (Hevy: 30) |", hevy)


