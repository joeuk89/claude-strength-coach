class StreakTest(PagesCase):
    def setUp(self):
        super().setUp()
        doc = self.overlay_doc()
        for start, created in (("2026-09-21", "2026-09-20"), ("2026-09-28", "2026-09-27"),
                               ("2026-10-05", "2026-10-04")):
            self.write_overlay(self.shifted(doc, start, created), f"{start}-weekly")

    @staticmethod
    def shifted(doc, start, created):
        offset = (date.fromisoformat(start) - date(2026, 10, 12)).days
        moved = copy.deepcopy(doc)
        moved.update(id=f"{start}-weekly", created_at=f"{created}T18:00:00Z", approval=None,
                     span={"start": start, "end": (date.fromisoformat(start).toordinal() + 6)})
        moved["span"]["end"] = date.fromordinal(moved["span"]["end"]).isoformat()
        for session in moved["sessions"]:
            session["date"] = date.fromordinal(date.fromisoformat(session["date"]).toordinal() + offset).isoformat()
        return moved

    def streak_line(self):
        self.render()
        return section(self.page("progress.md"), "Core-complete weeks")

