def section(text, heading):
    """The lines under `## heading`, up to the next heading."""
    lines = text.splitlines()
    start = lines.index(f"## {heading}") + 1
    found = []
    for line in lines[start:]:
        if line.startswith("## "):
            break
        found.append(line)
    return [line for line in found if line]


def headings(text):
    return [line[3:] for line in text.splitlines() if line.startswith("## ")]


def without_as_of(text):
    return UPDATED.sub("Updated <time>", TIMESTAMP.sub("<as-of>", text))


class PagesCase(HistoryCase):
    """A copy of valid/ with the C14 workouts plus Session A trained on 2026-10-12, synced to history."""

    def setUp(self):
        super().setUp()
        self.env = {"COACH_NOW": NOW}
        self.workouts = fixture_workouts() + [session_a_workout()]
        self.cache(self.workouts)
        self.sync()

    def add_workouts(self, *extra):
        self.workouts += list(extra)
        self.cache(self.workouts)
        self.sync()

    def render(self, *argv, expect=0, env=None):
        return self.coach("pages", "render", *argv, expect=expect, env=env)

    def page(self, name):
        return (self.root / name).read_text(encoding="utf-8")

    def brief(self, *argv, env=None):
        self.render("--only", "brief", *argv, env=env)
        return self.page("this-week.md")

    def overlay_doc(self):
        return read_json(self.root / OVERLAY)

    def write_overlay(self, doc, overlay_id=WEEKLY):
        write_json(self.root / "data" / "overlays" / f"{overlay_id}.json", doc)

    def check(self, ids, expect=0, env=None):
        return self.coach("check", "--only", ids, expect=expect, env=env)["data"]["results"]


