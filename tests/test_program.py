class RenderTest(unittest.TestCase):
    def test_pages_start_with_the_header(self):
        pages = program.render_all(VALID)
        self.assertEqual(sorted(pages), PAGES)
        for path, text in pages.items():
            with self.subTest(path=path):
                self.assertEqual(text.splitlines()[0], HEADER)
                self.assertTrue(text.endswith("\n"))

    def test_db_bench_row_shows_both_numbers(self):
        page = program.render_all(VALID)["routine/session-a.md"]
        bench = [line for line in page.splitlines() if line.startswith("| Bench Press (Dumbbell)")]
        self.assertEqual(len(bench), 1, page)
        self.assertIn("25/hand (Hevy: 50)", bench[0])

    def test_committed_valid_pages_are_fresh(self):
        for path, text in program.render_all(VALID).items():
            with self.subTest(path=path):
                self.assertEqual((VALID / path).read_bytes().decode("utf-8"), text)

    def test_top_set_and_back_offs_render_as_two_rows(self):
        page = program.render_all(INSTANCES / "program-top-set")["routine/session-a.md"]
        lines = page.splitlines()
        start = next(i for i, line in enumerate(lines) if line.startswith("| Back Squat (Barbell)"))
        self.assertIn("| 1×3 |", lines[start])
        self.assertTrue(lines[start + 1].startswith("|  | 3×5 |"), lines[start + 1])

    def test_program_page_lists_every_session(self):
        page = program.render_all(VALID)["routine/program.md"]
        self.assertIn("[Session A](session-a.md)", page)
        self.assertIn("[Session B](session-b.md)", page)


class RenderCommandTest(EnvelopeMixin, unittest.TestCase):
    def test_render_writes_pages_and_a_second_run_changes_nothing(self):
        with Instance() as root:
            shutil.rmtree(root / "routine")
            data = self.run_ok("--root", str(root), "program", "render")
            self.assertEqual(sorted(data["written"]), PAGES)
            first = {p: (root / p).read_bytes() for p in PAGES}
            for path in PAGES:
                self.assertEqual(first[path].decode("utf-8").splitlines()[0], HEADER)
            self.assertIn(b"25/hand (Hevy: 50)", first["routine/session-a.md"])
            data = self.run_ok("--root", str(root), "program", "render")
            self.assertEqual(data["written"], [])
            self.assertEqual(sorted(data["unchanged"]), PAGES)
            self.assertEqual({p: (root / p).read_bytes() for p in PAGES}, first)

    def test_dry_run_writes_nothing(self):
        with Instance() as root:
            shutil.rmtree(root / "routine")
            data = self.run_ok("--root", str(root), "program", "render", "--dry-run")
            self.assertFalse((root / "routine").exists())
        self.assertEqual(sorted(data["would_write"]), PAGES)

    def test_render_removes_a_page_it_wrote_for_a_removed_session(self):
        with Instance() as root:
            doc = read_program(root)
            doc["sessions"] = doc["sessions"][:1]
            doc["schedule"]["params"]["days"].pop("thu")
            write_program(root, doc)
            (root / "routine" / "notes.md").write_text("hand-written\n", encoding="utf-8")
            data = self.run_ok("--root", str(root), "program", "render")
            self.assertFalse((root / "routine" / "session-b.md").exists())
            self.assertTrue((root / "routine" / "notes.md").exists())
        self.assertEqual(data["removed"], ["routine/session-b.md"])
        self.assertEqual(data["not_generated"], ["routine/notes.md"])

    def test_invalid_program_is_not_rendered(self):
        with Instance(INSTANCES / "program-unknown-exercise") as root:
            self.run_fail(1, "--root", str(root), "program", "render")
            self.assertFalse((root / "routine").exists())


def check(root, check_id):
    code, envelope, stderr = run_cli(["--root", str(root), "check", "--only", check_id])
    return code, envelope["data"]["results"]


class ChecksTest(unittest.TestCase):
    def assert_status(self, root, check_id, code, status):
        found_code, results = check(root, check_id)
        self.assertEqual(found_code, code, results)
        self.assertEqual({r["status"] for r in results}, {status}, results)
        return results

    def test_valid_instance_passes_every_program_check(self):
        for check_id in ("program_schema", "state_schema", "program_exercise_ids", "routine_render_fresh",
                         "avoided_in_program"):
            with self.subTest(check=check_id):
                self.assert_status(VALID, check_id, 0, "pass")

    def test_no_program_skips(self):
        for check_id in ("program_schema", "state_schema", "program_exercise_ids", "routine_render_fresh",
                         "avoided_in_program"):
            with self.subTest(check=check_id):
                self.assert_status(INSTANCES / "hevy-fresh", check_id, 0, "skip")

    def test_program_schema_fails(self):
        results = self.assert_status(INSTANCES / "program-bad-schema", "program_schema", 1, "fail")
        self.assertIn("load_mode", results[0]["message"])
        self.assertEqual(results[0]["path"], "data/program.json")

    def test_program_exercise_ids_fails_on_an_unknown_id(self):
        results = self.assert_status(INSTANCES / "program-unknown-exercise", "program_exercise_ids", 1, "fail")
        self.assertIn("no_such_exercise", results[0]["message"])

    def test_program_exercise_ids_fails_on_a_missing_load_mode(self):
        results = self.assert_status(INSTANCES / "program-bad-schema", "program_exercise_ids", 1, "fail")
        self.assertIn("load_mode", results[0]["message"])

    def test_stale_render_fixture_fails_naming_the_file(self):
        results = self.assert_status(INSTANCES / "program-stale-render", "routine_render_fresh", 1, "fail")
        self.assertEqual([r["path"] for r in results], ["routine/session-a.md"])

    def test_one_character_edit_fails(self):
        with Instance() as root:
            page = root / "routine" / "session-a.md"
            text = page.read_text(encoding="utf-8")
            page.write_text(text.replace("brace", "Brace", 1), encoding="utf-8")
            results = self.assert_status(root, "routine_render_fresh", 1, "fail")
        self.assertEqual(results[0]["path"], "routine/session-a.md")
        self.assertIn("program render", results[0]["message"])

    def test_missing_and_extra_pages_fail(self):
        with Instance() as root:
            (root / "routine" / "session-b.md").unlink()
            (root / "routine" / "legacy.md").write_text("old notes\n", encoding="utf-8")
            results = self.assert_status(root, "routine_render_fresh", 1, "fail")
        self.assertEqual(sorted(r["path"] for r in results), ["routine/legacy.md", "routine/session-b.md"])

    def test_avoided_in_program_warns(self):
        code, results = check(INSTANCES / "program-avoided", "avoided_in_program")
        self.assertEqual(code, 0, results)
        self.assertEqual([r["status"] for r in results], ["warn"])
        self.assertIn("db_bench_press", results[0]["message"])
        self.assertIn("session-a", results[0]["message"])

    def test_avoided_exercise_in_a_parked_session_passes(self):
        with Instance(INSTANCES / "program-avoided") as root:
            doc = read_program(root)
            doc["sessions"][0]["status"] = "parked"
            write_program(root, doc)
            self.assert_status(root, "avoided_in_program", 0, "pass")

    def test_state_schema_fails(self):
        results = self.assert_status(INSTANCES / "state-bad-schema", "state_schema", 1, "fail")
        self.assertIn("$.block.light_week.status", results[0]["message"])
        self.assertEqual(results[0]["path"], "data/state.json")


