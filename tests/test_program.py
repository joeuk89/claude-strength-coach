HEADER = ("<!-- generated by coach from data/program.json; edit the data, then run: "
          "python3 -m coach program render -->")
PAGES = ["routine/program.md", "routine/session-a.md", "routine/session-b.md"]


class Instance:
    """A temporary copy of a fixture instance (valid/ by default)."""

    def __init__(self, source=VALID):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        shutil.copytree(source, self.root, dirs_exist_ok=True)

    def __enter__(self):
        return self.root

    def __exit__(self, *exc):
        self._tmp.cleanup()


def read_program(root):
    return json.loads((root / "data" / "program.json").read_text(encoding="utf-8"))


def write_program(root, doc):
    (root / "data" / "program.json").write_text(json.dumps(doc, indent=2), encoding="utf-8")


def problem_paths(doc, root=VALID):
    found = program.problems(doc, config_module.load(root), Library.load(root))
    return [(kind, error.path, error.message) for kind, error in found]


def valid_doc():
    return read_program(VALID)


class LoadTest(unittest.TestCase):
    def test_valid_program_loads(self):
        doc = program.load(VALID)
        self.assertEqual([s["id"] for s in doc["sessions"]], ["session-a", "session-b"])

    def test_a_session_without_location_loads_as_null(self):
        doc = valid_doc()
        del doc["sessions"][0]["location"]
        with Instance() as root:
            write_program(root, doc)
            self.assertIsNone(program.load(root)["sessions"][0]["location"])
            self.assertEqual(problem_paths(doc, root), [])

    def test_missing_program(self):
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaises(ValidationError) as caught:
                program.load(tmp)
        self.assertIn("data/program.json", caught.exception.message)

    def test_older_version_names_the_migration(self):
        doc = valid_doc()
        doc["schema_version"] = 0
        with Instance() as root:
            write_program(root, doc)
            with self.assertRaises(ValidationError) as caught:
                program.load(root)
        self.assertIn("migrate run", caught.exception.message)


class ProblemsTest(unittest.TestCase):
    def test_valid_program_has_none(self):
        self.assertEqual(problem_paths(valid_doc()), [])

    def assert_problem(self, doc, path, text=None, kind=program.SCHEMA_PROBLEM):
        found = problem_paths(doc)
        matches = [p for p in found if p[1] == path and p[0] == kind and (text is None or text in p[2])]
        self.assertTrue(matches, found)

    def test_both_reps_and_rep_range(self):
        doc = valid_doc()
        doc["sessions"][0]["exercises"][0]["sets"][0]["rep_range"] = {"start": 3, "end": 5}
        self.assert_problem(doc, "$.sessions[0].exercises[0].sets[0]", "not both")

    def test_neither_reps_nor_rep_range(self):
        doc = valid_doc()
        del doc["sessions"][0]["exercises"][0]["sets"][0]["reps"]
        self.assert_problem(doc, "$.sessions[0].exercises[0].sets[0]", "reps or rep_range")

    def test_timed_modes_need_their_measure(self):
        doc = valid_doc()
        exercise = doc["sessions"][1]["exercises"][1]
        exercise.update(load_mode="duration", start_load=None)
        exercise["sets"] = [{"count": 3, "type": "normal"}]
        self.assert_problem(doc, "$.sessions[1].exercises[1].sets[0]", "duration_seconds")
        exercise["sets"] = [{"count": 3, "type": "normal", "duration_seconds": 30}]
        self.assertEqual(problem_paths(doc), [])

    def test_rep_range_backwards(self):
        doc = valid_doc()
        doc["sessions"][0]["exercises"][1]["sets"][0]["rep_range"] = {"start": 10, "end": 8}
        self.assert_problem(doc, "$.sessions[0].exercises[1].sets[0].rep_range", "above end")

    def test_start_load_on_an_unloaded_mode(self):
        doc = valid_doc()
        doc["sessions"][1]["exercises"][1]["load_mode"] = "band"
        self.assert_problem(doc, "$.sessions[1].exercises[1].start_load", "band")

    def test_duplicate_session_ids(self):
        doc = valid_doc()
        doc["sessions"][1]["id"] = "session-a"
        self.assert_problem(doc, "$.sessions[1].id", "session-a")

    def test_reserved_session_id(self):
        doc = valid_doc()
        doc["sessions"][1]["id"] = "program"
        self.assert_problem(doc, "$.sessions[1].id", "program.md")

    def test_exercise_twice_in_a_session(self):
        doc = valid_doc()
        doc["sessions"][0]["exercises"].append(copy.deepcopy(doc["sessions"][0]["exercises"][0]))
        self.assert_problem(doc, "$.sessions[0].exercises[2].exercise_id", "twice")

    def test_external_session_clashes_with_a_session(self):
        doc = valid_doc()
        doc["external_sessions"] = [{"id": "session-a", "title": "PT", "weekday": "tue", "estimated_sets": {}}]
        self.assert_problem(doc, "$.external_sessions[0].id", "session-a")

    def test_estimated_sets_take_library_muscles(self):
        doc = valid_doc()
        doc["external_sessions"] = [{"id": "pt-tue", "title": "PT", "weekday": "tue",
                                     "estimated_sets": {"chest": 3, "pecs": 2}}]
        self.assert_problem(doc, "$.external_sessions[0].estimated_sets.pecs", "not allowed")

    def test_missed_day_rule_names_a_session(self):
        doc = valid_doc()
        doc["missed_day_rules"] = [{"id": "miss-c", "session_id": "session-c", "text": None, "when": {},
                                    "action": {"kind": "skip"}}]
        self.assert_problem(doc, "$.missed_day_rules[0].session_id", "session-c")

    def test_unknown_scheme_name(self):
        doc = valid_doc()
        doc["sessions"][0]["exercises"][0]["scheme"]["name"] = "vibes"
        self.assert_problem(doc, "$.sessions[0].exercises[0].scheme.name")

    def test_unknown_exercise_is_an_exercise_id_problem(self):
        doc = valid_doc()
        doc["sessions"][0]["exercises"][0]["exercise_id"] = "no_such_exercise"
        self.assert_problem(doc, "$.sessions[0].exercises[0].exercise_id", "no_such_exercise",
                            kind=program.EXERCISE_PROBLEM)

    def test_top_set_and_back_off_groups_validate(self):
        doc = read_program(INSTANCES / "program-top-set")
        self.assertEqual(problem_paths(doc, INSTANCES / "program-top-set"), [])


